@needs_stack
@pytest.mark.parametrize("mode", ["candidate", "purity", "minimal"])
def test_author_family_adocument_modes(s0e_doc, mode):
    ad = FA.author_family_adocument(s0e_doc, mode=mode)
    r = ad["report"]
    g = r["gates"]
    assert g["decodes_clean"] and g["roundtrip_equal"]
    assert g["dangling_after_schema_census"] == 0
    assert g["byte_scan_donor_ids"]["hits"] == 0     # ZERO donor element ids
    assert g["donor_name_hits"] == []                # ZERO donor / employee names
    assert ad["value"]["m_ownerFamilyId"] == s0e_doc.self_family.elem_id
    live = {e.elem_id for e in s0e_doc.elements}
    # nothing referenced that is not ours (the naive collector also counts
    # small counters; the schema census above is the authority)
    assert all(i in live or i < 100 for i in g["our_ids_referenced"])
    if mode == "purity":
        assert r["forge_corpus"]["action"] == "EMPTIED"
        assert len(ad["payload"]) < 50_000
    else:
        assert r["forge_corpus"]["action"] == "CARRIED"
    if mode == "minimal":
        # only the owner names ours: no registry indexes our elements
        assert g["byte_scan_our_ids"]["distinct"] <= 1


@needs_stack
def test_candidate_indexes_exactly_our_settings_layer(s0e_doc):
    ad = FA.author_family_adocument(s0e_doc, mode="candidate")
    inv = ad["inventory"]
    tree = ad["value"]
    dbv = FA._appinfo_body(tree, "DBViewInfo")
    assert dbv["m_DBViewProjectId"] == inv.project_view
    assert dbv["m_DBViewsIndex"] == inv.all_views
    assert dbv["m_aidSunAndShadowSettings"] == inv.suns
    dat = FA._appinfo_body(tree, "DatumTracking")
    assert dat["m_elemIdSet"] == sorted(inv.levels + inv.refplanes)
    assert FA._appinfo_body(tree, "UnitsTracking")["m_unitsElemId"] == inv.units_elem
    # the built-in category catalogue: ours has none
    ctr = FA._appinfo_body(tree, "CategoryTracking")
    assert ctr["m_gstyleData"] == [] and ctr["m_categoryData"] == []
    # the settings-singleton table is all-null (K5-at-family-scale residual)
    uet = FA._appinfo_body(tree, "UniqueElementsTracking")["m_elemIds"]
    assert all(x == -1 for x in uet) and len(uet) == 93
    # no nested families: exactly the self entry
    fm = FA._appinfo_body(tree, "FamilyMgr")["m_arrLoadedFamilyInfo"]
    assert fm == [{"m_surrogateId": -1, "m_familyDocGUIDs": []}]
    # the product build constant, not the archetype's save lineage
    assert [b["m_str"] for b in tree["m_storedByRevitBuild"]] == [FA.PRODUCT_BUILD_STRING_2026]
    # sample naming memory gone
    assert FA._appinfo_body(tree, "NewItemNumber")["m_items"] == []
    assert "Elevation 0" not in " ".join(_all_strings(tree))


