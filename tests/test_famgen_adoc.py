def test_end_record_is_the_decoded_10_byte_constant():
    assert FA.FAMILY_END_RECORD == bytes.fromhex("a30300000000ffffffff")
    tag, a, b = struct.unpack("<Hii", FA.FAMILY_END_RECORD)
    assert (tag, a, b) == (0x3A3, 0, -1)
    assert len(FA.FAMILY_END_RECORD) == 10


def test_signature_string_wire_form():
    assert FA.DATA_GENERATED_STRING == "Data generated by Autodesk® Revit®"
    n = struct.unpack_from("<I", FA.FOOTER_STRING_BYTES, 0)[0]
    assert n == len(FA.DATA_GENERATED_STRING) == 34
    assert FA.FOOTER_STRING_BYTES[4:] == FA.DATA_GENERATED_STRING.encode("utf-16-le")
    assert len(FA.FOOTER_STRING_BYTES) == 4 + 68


def test_signature_matches_the_writer_constant():
    # the string this stream classifies is the SAME constant the writer emits
    from rvt.famgen import skeleton as fs
    assert fs.DATA_GENERATED_STRING == FA.DATA_GENERATED_STRING


def test_build_footer_nonce_shape_and_determinism():
    b1 = FA.build_footer(guid="11111111-2222-3333-4444-555555555555", payload=b"abc")
    b2 = FA.build_footer(guid="11111111-2222-3333-4444-555555555555", payload=b"abc")
    b3 = FA.build_footer(guid="11111111-2222-3333-4444-555555555555", payload=b"abd")
    b4 = FA.build_footer(guid="99999999-2222-3333-4444-555555555555", payload=b"abc")
    assert len(b1) == FA.FOOTER_BLOB_LEN == 64
    assert b1 == b2                      # deterministic
    assert b1 != b3 and b1 != b4         # depends on payload + guid


def test_build_footer_empty_form_and_bad_mode():
    assert FA.build_footer(mode="empty") == b""
    with pytest.raises(ValueError):
        FA.build_footer(mode="checksum")


def test_footer_wire_layout():
    blob = b"\xaa" * 64
    wire = FA.footer_wire(blob)
    assert wire[:2] == struct.pack("<H", 0x0F28)          # terminator tag
    assert wire[2:18] == b"\x00" * 16
    tag, n = struct.unpack_from("<HI", wire, 18)
    assert tag == 0x0F3F and n == 64
    assert wire[24:88] == blob
    assert wire.endswith(FA.FOOTER_STRING_BYTES)


def test_footer_tokens_classify_every_region():
    kinds = {v["status"] for v in FA.FOOTER_TOKENS.values()}
    assert kinds == {"format", "ours", "retired"}
    assert FA.FOOTER_TOKENS["footer_string"]["status"] == "format"
    assert FA.FOOTER_TOKENS["footer_blob_bytes"]["status"] == "ours"
    assert FA.FOOTER_TOKENS["end_record_donor_parity"]["status"] == "retired"


@needs_rfa
def test_footer_forensics_on_the_archetype():
    """The corpus proof on the archetype alone: signature present, blob 64 B,
    the true end record is the constant, unframe/reframe byte-exact, and the
    depaged 'tail' is the raw file's own final-block parity."""
    rep = FA.footer_forensics(files=[RFA], with_digest_tests=True)
    assert rep["units"] >= 1
    assert rep["string"]["universal"] is True
    assert rep["string"]["occurrences"].get(FA.DATA_GENERATED_STRING) == 1
    assert rep["blob"]["lengths"].get(64) == 1
    assert rep["blob"]["digest_tests"]["matches"] == []
    ends = rep["end_record"]["streams"]
    assert len(ends) == 1
    e = ends[0]
    assert e["true_end_record"] == FA.FAMILY_END_RECORD.hex()
    assert e["true_end_record_is_constant"] is True
    assert e["unframe_reframe_byte_exact"] is True
    # the depaged walker's "end record" carried extra bytes = the final
    # block's CRCIO parity (framing, not content)
    assert e["walker_end_record_len"] > len(FA.FAMILY_END_RECORD)
    assert e["junk_is_raw_final_block_parity"] is True


