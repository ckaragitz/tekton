def _all_strings(v, out=None):
    if out is None:
        out = []
    if isinstance(v, dict):
        for x in v.values():
            _all_strings(x, out)
    elif isinstance(v, list):
        for x in v:
            _all_strings(x, out)
    elif isinstance(v, str) and v:
        out.append(v)
    return out
