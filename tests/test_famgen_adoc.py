@needs_stack
def test_emit_v2_reads_back_clean(tmp_path, s0e_doc):
    out = str(tmp_path / "s0e_v2.rfa")
    rep = FA.emit_family_rfa_v2(s0e_doc, out, write_reports=False)
    v = rep["verify"]
    assert v["ok"] is True
    assert v["gzip_crc_failures"] == 0 and v["ecc_mismatch"] == 0
    assert not v["walker_errors"] and v["id_sets_identical_across_seqs"]
    # ours: the footer blob + the decoded end record
    assert rep["footer_blob_len"] == 64
    assert rep["end_record_hex"] == FA.FAMILY_END_RECORD.hex()
    # identity through rvt.identity
    assert rep["identity"]["author"] == FA.PRODUCT_NAME
    assert rep["identity"]["unique_document_guid"] == rep["identity"]["central_episode_guid"]
    # the ONE carried stream is the certified schema constant
    assert [c["stream"] for c in rep["carried"]] == ["Formats/Latest"]
    assert rep["carried"][0]["is_corpus_schema_constant"] is True


@needs_stack
def test_emit_v2_validates_and_is_provenance_clean(tmp_path, s0e_doc):
    out = str(tmp_path / "s0e_v2.rfa")
    FA.emit_family_rfa_v2(s0e_doc, out, write_reports=False)
    val = FA.validate_family_file(out, with_donor_parity=False)
    assert val["ok"] is True
    assert val["family_mode"]["verdict"] == "VALID"
    assert val["family_mode"]["n_errors"] == 0
    prov = FA.provenance_scan_v2(out)
    assert prov["ok"] is True, {k: v for k, v in prov["checks"].items() if not v}
    a = prov["adocument"]
    assert a["decodes_clean"] and a["byte_scan_donor_ids"]["hits"] == 0
    assert a["dangling_id_refs_gt99"] == 0 and a["donor_name_string_hits"] == []
    pf = prov["partition_footer"]
    assert pf["signature_string_occurrences"] == 1
    assert pf["end_record_is_decoded_constant"] is True
    assert pf["donor_footer_blob_present"] is False
    assert pf["donor_end_parity_present"] is False
    idn = prov["identity"]
    assert idn["no_employee_usernames"] and idn["no_windows_user_path"]
    assert idn["author"] == FA.PRODUCT_NAME


