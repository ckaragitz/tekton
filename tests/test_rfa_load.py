ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))

from rvt.convert import rfa_load as RL                     # noqa: E402
from rvt.frontdoor import router as R                      # noqa: E402


def _pinned_base(target=None):
    try:
        from rvt.frontdoor.base import resolve_base
        return resolve_base(target_release=target).path
    except Exception:
        return None


PINNED_BASE = _pinned_base()
PINNED_2025 = _pinned_base(2025)
needs_pin = pytest.mark.skipif(PINNED_BASE is None, reason="pinned genesis base absent")
needs_pin_2025 = pytest.mark.skipif(PINNED_2025 is None,
                                    reason="pinned 2025 genesis base absent")


def _catalog_ok() -> bool:
    try:
        from rvt.famgen import factory as F
        F.resolve_panelboard_facts("eaton", "pow-r-line", mains_a=400, spaces=42,
                                   voltage="480Y/277", mcb=True, mounting="surface",
                                   panel_name="X")
        return True
    except Exception:
        return False


needs_catalog = pytest.mark.skipif(not _catalog_ok(), reason="famgen catalog absent")


@pytest.fixture(scope="module")
def panel_rfa(tmp_path_factory):
    """OUR generated panelboard .rfa (start_id=1000, family-mode VALID)."""
    if not _catalog_ok():
        pytest.skip("famgen catalog absent")
    from rvt.famgen import factory as F
    out = tmp_path_factory.mktemp("rfa") / "DP-1.rfa"
    prod = F.make_panelboard(vendor="eaton", line="pow-r-line", mains_a=400,
                            spaces=42, voltage="480Y/277", mcb=False,
                            mounting="surface", panel_name="DP-1")
    rep = prod.write(str(out), validate=True)
    assert rep["ok"], rep
    return str(out)


def _validator_errors(path: str) -> int:
    from rvt import validate as V
    vr = V.validate_file(path)
    return sum(1 for f in vr.findings if f.severity == V.SEV_ERROR)


