def test_matrix_names_the_new_lane_and_keeps_its_evidence_honest():
    from rvt.frontdoor import matrix as M
    for key in ((("rfa",), "rvt"), (("rfa", "rvt"), "rvt")):
        cell = M.CELLS[M.key_for(*key)]
        assert "rfa-born-load" in cell.stages and "rfa-classify" in cell.stages
        assert any("rvt.convert.rfa_load" in c and "needs-viewer" in c for c in cell.caveats)
    assert M.STAGES["rfa-born-load"].impl == "rvt.convert.rfa_load:load_rfa_into_project"
    # hard problems only: a certified binary absent on disk is the expected
    # fresh-clone state (experiments/**/*.rvt are git-ignored), soft-marked
    problems = [p for p in M.verify_evidence()
                if M.ABSENT_BINARY_MARK not in p
                and ("rfa_load" in p or "rfa-born" in p or "rfa-classify" in p)]
    assert problems == [], problems
