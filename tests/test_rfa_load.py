"""rvt.convert.rfa_load -- the standalone-born .rfa LOAD lane (issue #99).

Fresh-clone runnable (no samples/, no ifcopenshell): OUR own panelboard
.rfa is generated by rvt.famgen.factory at start_id=1000 (standalone-born
by construction) and loaded onto the pinned, plugin-bundled genesis base
through the schema-typed id remap + rvt.famload; then the same file goes
through the product router (`rfa -> rvt`) for the default release and for
--target-version 2025.

What is asserted is what OUR gates can prove -- project validator 0
errors, four-registry census coherent, the loaded family present in all
four registries, the id law honoured.  Autodesk's reader is the arbiter of
"loads" (rule 4): the MECHANISM is certified as T2a in the ledger, these
artifacts are not, and the route says so.
"""
from __future__ import annotations

