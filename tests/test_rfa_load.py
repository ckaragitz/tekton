@needs_catalog
@needs_pin
def test_load_our_rfa_onto_the_pinned_base_validates_zero_errors(panel_rfa, tmp_path):
    from rvt.famload import four_registry_census
    out = str(tmp_path / "DP-1_loaded.rvt")
    rec = RL.load_rfa_into_project(panel_rfa, PINNED_BASE, out)
    assert rec["ok"] is True, rec
    assert os.path.isfile(out) and os.path.isfile(out + ".load.json")
    assert rec["validate"]["verdict"] == "VALID" and rec["validate"]["n_errors"] == 0
    assert rec["registries"]["coherent"] is True and rec["registries"]["ours_in_all_four"] is True
    assert rec["family_inventory_ok"] is True
    wm = rec["host_watermark"]
    assert rec["rebase"]["start_id"] == wm + 1                     # T2a's allocation law
    lo, hi = rec["ids"]["doc_id_range"]
    assert lo == wm + 1 and rec["ids"]["host_family"] == hi + 1
    assert rec["ids"]["twins"] == 14                                # one twin per family parameter
    # independent gates on the written file
    assert _validator_errors(out) == 0
    census = four_registry_census(out)
    assert census["coherent"] is True and census["save_units"] == 2


@needs_catalog
@needs_pin
def test_route_rfa_to_rvt_loads_our_standalone_born_rfa(panel_rfa, tmp_path):
    """THE flipped cell (issue #99): `route run --output rvt --rfa ours.rfa`
    delivers a loaded project instead of the clear line."""
    res = R.route({"rfa": panel_rfa}, "rvt", out=str(tmp_path / "o"))
    assert res.ok is True, res.errors + [res.status, res.line]
    assert res.route == "rfa_load" and res.line == ""
    stages = [s["stage"] for s in res.steps]
    assert stages == ["rfa-classify", "rfa-born-load"], stages
    assert "id-remap lane" in res.status and "VALID 0 errors" in res.status
    loaded = res.files["loaded_rvt"]
    assert os.path.isfile(loaded) and os.path.isfile(res.files["load_report"])
    assert _validator_errors(loaded) == 0
    cav = " ".join(res.caveats)
    assert "STANDALONE-BORN" in cav and RL.CERTIFIED_BY in cav
    assert "THIS artifact is not" in cav                            # never "loads in Revit"
    man = json.load(open(res.manifest_paths["route.json"]))
    assert man["ok"] is True and man["files"]["loaded_rvt"]


@needs_catalog
@needs_pin_2025
def test_route_rfa_to_rvt_target_2025_loads_onto_the_2025_base(panel_rfa, tmp_path):
    """--target-version 2025 with no --rvt: the default host becomes the
    certified 2025 base and the load runs under that release."""
    from rvt import versions as V
    res = R.route({"rfa": panel_rfa}, "rvt", out=str(tmp_path / "o"), target_version=2025)
    assert res.ok is True, res.errors + [res.status, res.line]
    assert (res.target_version or {}).get("status") == "match"
    loaded = res.files["loaded_rvt"]
    assert V.detect_release(loaded) == 2025
    assert res.releases.get("loaded_rvt") == 2025
    assert _validator_errors(loaded) == 0


