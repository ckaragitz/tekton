def _profile_key(cat_id: int, gtype: int) -> str:
    return f"{int(cat_id)}:{int(gtype)}"


def _apply_row_profile(rec: TypeRecord, prof: Optional[dict]) -> None:
    """Stamp the per-category ElementHeader flag word onto the row's
    seq-101 header (the low byte is a per-category compiled-in property;
    the cell-list era bit is never set -- our rows carry no CellList) and
    record the profile in ``refs`` for the linter."""
    if not prof:
        return
    ab = int(prof.get("ab") or 0) & ~AB_CELLLIST_BIT
    if ab:
        rec.header["m_abFlags4Bytes"] = ab
    vis = prof.get("vis")
    if vis is not None:
        (rec.header.get("m_viewRules") or {})["m_nVisibleViewFlags"] = int(vis)
    rec.refs["profile"] = {k: prof.get(k) for k in
                           ("ab", "pattern", "material", "screen_sized", "pen")}


def _resolve_pattern(prof: Optional[dict], wired: Optional[int],
                     default: int) -> Tuple[int, Optional[str]]:
    """(pattern id, note) for a row: the profile's STRICT rule first
    ('null' = no cell / 'builtin:<id>' = the one built-in pattern the key
    always carries / 'elem' = always a document pattern -> the caller's
    ``wiring``), else OUR default (solid) or the null default for the
    mixed 'nullwire' keys.  Wiring is honoured ONLY on strict 'elem' keys:
    everywhere else the pattern is OUR graphic choice."""
    rule = (prof or {}).get("pattern", "solid")
    if rule == "null":
        return INVALID, None
    if rule == "nullwire":
        return INVALID, None                              # null is in-set: our default
    if isinstance(rule, str) and rule.startswith("builtin:"):
        return int(rule.split(":", 1)[1]), None
    if rule == "elem":
        if wired is not None and int(wired) not in (0, INVALID):
            return int(wired), None
        return int(default), "pattern:elem-key without wiring (default solid)"
    return int(default), None                              # 'solid'


def _resolve_material(prof: Optional[dict], wired: Optional[int],
                      default: int) -> Tuple[int, Optional[str]]:
    """(material id, note): the strict rule ('null' / 'builtin:<id>' /
    'elem' -> ``wiring``); 'nullwire' and unknown -> OUR default (-1)."""
    rule = (prof or {}).get("material", "null")
    if rule in ("null", "nullwire"):
        return INVALID, None
    if isinstance(rule, str) and rule.startswith("builtin:"):
        return int(rule.split(":", 1)[1]), None
    if rule == "elem":
        if wired is not None and int(wired) not in (0, INVALID):
            return int(wired), None
        return int(default), "material:elem-key without wiring (default -1)"
    return int(default), None


def _resolve_pen(prof: Optional[dict], ours: int) -> int:
    rule = (prof or {}).get("pen", "ours")
    if rule == "null0":
        return 0
    if rule == "nullneg1":
        return -1
    return int(ours)


def builtin_style_catalog(ids: IdArg, *,
                          enum: Optional[dict] = None,
                          exclude_categories: Iterable[int] = (),
                          material_id: int = INVALID,
                          line_pattern_id: int = LINEPATTERN_SOLID,
                          scheme: Optional[Dict[str, Tuple[int, int, int]]] = None,
                          profile: Optional[dict] = None,
                          use_profile: bool = True,
                          wiring: Optional[Dict[Tuple[int, int], dict]] = None,
                          id_map: Optional[Dict[Tuple[int, int], int]] = None,
                          ) -> List[TypeRecord]:
    """The COMPLETE built-in-category object-styles table: one projection
    ``GStyleElem`` per enum category + one cut ``GStyleElem`` per CUTTABLE
    category, coloured / weighted by OUR discipline scheme
    (``house_standard.HOUSE_SCHEME``: discipline -> (projection pen, cut
    pen, colour)) and SHAPED by the per-key structural profile
    (:data:`PROFILE_FILE`): per-category header flag word, the pattern /
    pen null cells, the screen-sized flag and the built-in material ids
    (format constants), plus optional document ``wiring`` = ``{(category,
    type): {'material_id', 'line_pattern_id'}}`` for the keys the profile
    marks 'elem' (their material / pattern is a reference to a document
    element the caller owns -- the substitution rung passes the parent's).
    ``exclude_categories`` = categories the base document already styles
    (e.g. the 46 house-standard categories in G1_candidate) so the catalog
    COMPLETES the base instead of duplicating rows.  ``id_map`` =
    ``{(category, type): element id}`` pins rows to EXISTING ids (the
    in-place substitution probe: the row is rebuilt AT the id it already
    occupies).  ``use_profile=False`` reproduces the pre-fixer (uniform-
    shape) output for A/B probes.  Returns [TypeRecord, ...] (header key
    'GStyleElem:objectstyle')."""
    enum = enum or load_builtin_category_enum()
    prof_all = ((profile if profile is not None else load_builtin_style_profile())
                if use_profile else {"keys": {}})
    pkeys = prof_all.get("keys", {})
    sch = scheme or catalog_scheme()
    explicit = _explicit_disciplines()
    skip = set(int(c) for c in exclude_categories)
    wiring = wiring or {}
    id_map = id_map or {}
    out: List[TypeRecord] = []
    for row in enum["categories"]:
        cid = int(row["id"])
        if cid in skip:
            continue
        disc = classify_category(cid, explicit)
        ppen, cpen, colour = sch.get(disc, sch.get("general", (1, 3, 0)))
        for gtype, our_pen in ((1, ppen), (2, cpen)):
            if gtype == 2 and not row.get("cut"):
                continue
            prof = pkeys.get(_profile_key(cid, gtype)) if use_profile else None
            wired = wiring.get((cid, gtype)) or {}
            pat, pnote = _resolve_pattern(prof, wired.get("line_pattern_id"),
                                          line_pattern_id)
            mat, mnote = _resolve_material(prof, wired.get("material_id"), material_id)
            pen = _resolve_pen(prof, our_pen)
            screen = bool(prof.get("screen_sized")) if prof else False
            fixed_id = id_map.get((cid, gtype))
            rec = new_gstyle(cid, style_type=("cut" if gtype == 2 else "projection"),
                             pen=int(pen), color=int(colour), line_pattern_id=int(pat),
                             material_id=int(mat), screen_sized=screen,
                             ids=(None if fixed_id is not None else ids),
                             elem_id=(int(fixed_id) if fixed_id is not None else None))
            _apply_row_profile(rec, prof)
            rec.refs["discipline"] = disc
            for note in (pnote, mnote):
                if note:
                    rec.notes.append(note)
            out.append(rec)
    return out


def lint_builtin_style_catalog(records: Sequence[TypeRecord],
                               profile: Optional[dict] = None,
                               *, standalone: bool = True) -> dict:
    """The fixer's specimen LINT for the object-styles table: diff every
    row against the frozen per-key structural profile.  Hard findings =
    format-constant violations (header flag byte, pattern / pen null cells,
    screen-sized flag, built-in material id, gstyle type / owner / family
    shape); soft = document-wiring inputs left at their standalone
    defaults ('elem' keys with no wiring -- resolved by the substitution
    rung's parent wiring).  Returns {'hard': [...], 'soft': [...], 'rows':
    n, 'ok': hard == 0}."""
    prof_all = profile if profile is not None else load_builtin_style_profile()
    pkeys = prof_all.get("keys", {})
    hard: List[dict] = []
    soft: List[dict] = []
    seen_keys = set()
    for r in records:
        v = r.obj
        cid = int(v.get("m_categoryId"))
        gt = int(v.get("m_gstyleType"))
        key = _profile_key(cid, gt)
        seen_keys.add(key)
        prof = pkeys.get(key)
        gs = ((v.get("m_pGStyle") or {}).get("value") or {})
        hdr = r.header

        def bad(what, ours, want):
            hard.append({"id": r.elem_id, "key": key, "field": what,
                         "ours": ours, "expected": want})
        # universal shape
        if v.get("m_ownerId") != INVALID:
            bad("m_ownerId", v.get("m_ownerId"), INVALID)
        if v.get("m_famId") != INVALID:
            bad("m_famId", v.get("m_famId"), INVALID)
        if v.get("m_designOptionId") != INVALID:
            bad("m_designOptionId", v.get("m_designOptionId"), INVALID)
        if v.get("m_cellList") is not None:
            bad("m_cellList", "present", None)
        if hdr.get("m_categroryId") != INVALID:
            bad("hdr.m_categroryId", hdr.get("m_categroryId"), INVALID)
        if hdr.get("m_familyId") != INVALID:
            bad("hdr.m_familyId", hdr.get("m_familyId"), INVALID)
        if prof is None:
            hard.append({"id": r.elem_id, "key": key, "field": "key",
                         "ours": key, "expected": "a registered (category, type) key"})
            continue
        # per-key structural profile
        ab = int(hdr.get("m_abFlags4Bytes") or 0)
        want_ab = int(prof["ab"]) & ~AB_CELLLIST_BIT
        if (ab & 0xFF) != (want_ab & 0xFF):
            bad("hdr.m_abFlags4Bytes(low byte)", hex(ab), hex(want_ab))
        if ab & AB_CELLLIST_BIT:
            bad("hdr.m_abFlags4Bytes(cell-list bit)", hex(ab), "clear (no CellList)")
        if ab not in prof.get("ab_set", []) and ab != want_ab:
            bad("hdr.m_abFlags4Bytes(value)", hex(ab), [hex(x) for x in prof.get("ab_set", [])])
        vis = int(((hdr.get("m_viewRules") or {}).get("m_nVisibleViewFlags") or 0))
        if vis != int(prof.get("vis", -32768)):
            bad("hdr.m_nVisibleViewFlags", vis, prof.get("vis"))
        pat = gs.get("m_linePatternId")
        rule = prof.get("pattern")
        pat_ids = set(prof.get("pattern_builtin_ids") or [])
        if rule == "null" and pat != INVALID:
            bad("m_linePatternId", pat, "-1 (no pattern cell on this key)")
        elif isinstance(rule, str) and rule.startswith("builtin:") and pat != int(rule.split(":", 1)[1]):
            bad("m_linePatternId", pat, rule)
        elif rule == "elem" and (not isinstance(pat, int) or pat < 1):
            (soft if standalone else hard).append(
                {"id": r.elem_id, "key": key, "field": "m_linePatternId",
                 "ours": pat, "expected": "document-wired pattern element"})
        elif rule == "solid" and isinstance(pat, int) and pat < 0 and pat != INVALID \
                and pat not in pat_ids and pat != BUILTIN_SOLID_PATTERN:
            bad("m_linePatternId(builtin id)", pat, sorted(pat_ids))
        elif rule == "nullwire" and isinstance(pat, int) and pat < 0 and pat != INVALID:
            bad("m_linePatternId", pat, "-1 or a document pattern (nullwire key)")
        mat = gs.get("m_materialElemId")
        mrule = prof.get("material")
        if mrule == "null" and mat != INVALID:
            bad("m_materialElemId", mat, "-1")
        elif isinstance(mrule, str) and mrule.startswith("builtin:") and mat != int(mrule.split(":", 1)[1]):
            bad("m_materialElemId", mat, mrule)
        elif mrule == "elem" and (not isinstance(mat, int) or mat < 1):
            (soft if standalone else hard).append(
                {"id": r.elem_id, "key": key, "field": "m_materialElemId",
                 "ours": mat, "expected": "document-wired material element"})
        elif mrule == "nullwire" and isinstance(mat, int) and mat < 0 and mat != INVALID:
            bad("m_materialElemId", mat, "-1 or a document material (nullwire key)")
        if bool(gs.get("m_isScreenSized")) != bool(prof.get("screen_sized")):
            bad("m_isScreenSized", gs.get("m_isScreenSized"), prof.get("screen_sized"))
        pen = gs.get("m_penNumber")
        prule = prof.get("pen")
        if prule == "null0" and pen != 0:
            bad("m_penNumber", pen, 0)
        elif prule == "nullneg1" and pen != -1:
            bad("m_penNumber", pen, -1)
        elif prule == "ours":
            lo, hi = prof.get("pen_min"), prof.get("pen_max")
            if isinstance(pen, int) and pen == 0 and (lo is None or lo > 0):
                bad("m_penNumber", pen, "a real pen (key never carries the null pen)")
    return {"rows": len(records), "keys": len(seen_keys),
            "hard": hard, "soft": soft, "ok": not hard}


def catalog_report(records: Sequence[TypeRecord]) -> dict:
    """Counts per discipline / style type for the record + a round-trip
    proof over the whole catalog."""
    by_disc = collections.Counter(r.refs.get("discipline", "?") for r in records)
    by_type = collections.Counter(r.refs.get("style_type") for r in records)
    ok = 0
    fails = []
    for r in records:
        rep = r.roundtrip()
        if rep["ok"]:
            ok += 1
        else:
            fails.append({"elem_id": r.elem_id, "report": rep})
    return {"rows": len(records), "roundtrip_ok": ok,
            "by_discipline": dict(by_disc.most_common()),
            "by_style_type": {("projection" if k == 1 else "cut" if k == 2 else str(k)): v
                              for k, v in by_type.items()},
            "failures": fails[:5]}


