def _load_sample_documents(samples: Sequence[str]):
    """Yield ``(sample, Document)`` for each research-corpus sample -- the
    ONE place this module reads the corpus (the documented format-constant
    derivations below; nothing at generation time)."""
    from ..mutate import Document
    for s in samples:
        yield s, Document.load(s)


def derive_builtin_category_enum(samples: Sequence[str] = DERIVE_SAMPLES,
                                 verbose: bool = True) -> dict:
    """Derive the graphic-category ENUM: every built-in (negative) category
    id that carries a non-family-scoped object-style GStyleElem row in the
    HOST document of each sample, with the style TYPES present (1 =
    projection, 2 = cut).  Asserts the id set and the per-id type set are
    IDENTICAL across ``samples`` (else it is not a format constant) and
    returns {"categories": [{"id", "cut"}], ...}."""
    per_sample: Dict[str, Dict[int, set]] = {}
    for s, doc in _load_sample_documents(samples):
        rows: Dict[int, set] = collections.defaultdict(set)
        for gid in doc.ids_of_class("GStyleElem", host_only=True):
            v = doc.value(gid) or {}
            if v.get("m_famId", -1) != -1:            # family-scoped rows: content
                continue
            cid = v.get("m_categoryId")
            if isinstance(cid, int) and cid < 0:
                rows[cid].add(int(v.get("m_gstyleType", 1)))
        per_sample[s] = dict(rows)
        if verbose:
            print(f"   [enum] {s}: {len(rows)} built-in categories, "
                  f"{sum(1 for t in rows.values() if 2 in t)} cuttable")
    base = None
    for s, rows in per_sample.items():
        norm = {k: tuple(sorted(v)) for k, v in rows.items()}
        if base is None:
            base = norm
        elif norm != base:
            diff_ids = set(norm) ^ set(base)
            raise RuntimeError(f"graphic-category enum differs in {s}: "
                               f"{len(diff_ids)} ids differ (not a format constant?)")
    assert base is not None
    cats = [{"id": int(cid), "cut": 2 in ts} for cid, ts in sorted(base.items())]
    return {
        "generator": "rvt.genesis.catalog.derive_builtin_category_enum",
        "derived_from": list(per_sample),
        "note": ("The Revit-2026 graphic-category ENUM: every built-in category id "
                 "carrying an object-style row, plus its cuttability -- IDENTICAL "
                 "in every sample (a per-release registered constant, like the public "
                 "BuiltInCategory enum). Only ids and the cut flag are recorded: NO "
                 "pen / colour / pattern VALUE is read from any sample."),
        "count": len(cats),
        "cuttable": sum(1 for c in cats if c["cut"]),
        "categories": cats,
    }


def load_builtin_category_enum(path: str = ENUM_FILE, *,
                               derive_if_missing: bool = True) -> dict:
    """Load the frozen enum (derive + freeze it on first use)."""
    if os.path.exists(path):
        with open(path) as fh:
            return json.load(fh)
    if not derive_if_missing:
        raise FileNotFoundError(path)
    enum = derive_builtin_category_enum()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        json.dump(enum, fh, indent=1)
    return enum


