# ---------------------------------------------------------------------------
# 2. OUR classification RULES: category id -> discipline
# ---------------------------------------------------------------------------
#: The BuiltInCategory id space is allocated in decade BANDS by domain
#: (observed on the enum: -2000xxx architectural / annotation core,
#: -2001xxx model & site categories, -2002xxx detailing / mass / area,
#: -2003xxx information & analysis surfaces, -2004xxx dimension /
#: annotation styles, -2005xxx tags, -2006xxx datum heads & symbols,
#: -2007xxx connectors, -2008xxx MEP curves & devices, -2009xxx structural
#: & analytical, -2010xxx fabrication / systems analysis).  OUR RULE
#: colours a category by its band (the discipline it belongs to), except
#: the categories our house standard names explicitly (walls, ducts,
#: conduits ...), which take their listed discipline.  This is OUR
#: documented graphic-standard rule -- a mechanical classification, not
#: a copied per-category table.
BAND_DISCIPLINE: List[Tuple[int, int, str]] = [
    (-2001000, -2000000, "architectural"),   # walls/doors/windows/floors/stairs/lines
    (-2002000, -2001000, "architectural"),   # equipment, site, structure, links
    (-2003000, -2002000, "annotation"),      # detail items, area/mass surfaces
    (-2004000, -2003000, "general"),         # analysis / information categories
    (-2006000, -2004000, "annotation"),      # dimension styles, tags
    (-2007000, -2006000, "annotation"),      # datum heads, callouts, revisions
    (-2008000, -2007000, "electrical"),      # connectors
    (-2009000, -2008000, "mechanical"),      # MEP curves & devices (see refinements)
    (-2010000, -2009000, "structural"),      # structural / analytical
    (-2011000, -2010000, "general"),         # fabrication, systems analysis
]

#: refinements inside the MEP band (-2008xxx): piping vs electrical
#: sub-ranges of the enum [ids per the public BuiltInCategory allocation:
#: 20080xx ducts / duct devices; 200804x-200806x pipes & plumbing;
#: 200807x-200814x electrical devices, wire, cable tray, conduit].
def _mep_subdiscipline(cat_id: int) -> str:
    n = -cat_id - 2008000          # 0..999 within the MEP band
    if 40 <= n <= 69:
        return "piping"
    if 70 <= n <= 144:
        return "electrical"
    return "mechanical"


def _explicit_disciplines() -> Dict[int, str]:
    """Categories our house standard classifies explicitly (its
    HOUSE_CATEGORIES table) -- these override the band rule."""
    from . import house_standard as hs
    return {int(cid): disc for cid, _lbl, disc, _cut in hs.HOUSE_CATEGORIES}


#: OUR INK: the catalog's neutral line-work colour is a rich near-black
#: (RGB 24,24,24), not pure #000000 -- a common CAD/plot-standard choice
#: (our "layer black") that also makes every catalog row OURS by value:
#: Autodesk's per-category defaults use pure black hairlines for hundreds
#: of categories, and a (pen 1, #000000, solid) row would be value-identical
#: to theirs with no expression on either side.  Pure black stays reserved
#: for the house standard's own 46 named categories (hs.HOUSE_CATEGORIES
#: rows, built by the house standard, not by this generator).
INK_BLACK = 0x181818                       # COLORREF r|g<<8|b<<16 (grey => symmetric)


def catalog_scheme() -> Dict[str, Tuple[int, int, int]]:
    """OUR CATALOG colour scheme = the house discipline scheme
    (``house_standard.HOUSE_SCHEME``: discipline -> (projection pen, cut
    pen, colour)) with the neutral disciplines' pure black replaced by
    :data:`INK_BLACK` for the generated (non-house) categories."""
    from . import house_standard as hs
    out = {}
    for disc, (ppen, cpen, col) in hs.HOUSE_SCHEME.items():
        out[disc] = (int(ppen), int(cpen), INK_BLACK if int(col) == 0 else int(col))
    return out


def classify_category(cat_id: int, explicit: Optional[Dict[int, str]] = None) -> str:
    """OUR discipline for a built-in category id (rule: explicit house
    classification, else the MEP sub-range, else the id BAND)."""
    exp = explicit if explicit is not None else _explicit_disciplines()
    if cat_id in exp:
        return exp[cat_id]
    if -2009000 < cat_id <= -2008000:
        return _mep_subdiscipline(cat_id)
    for lo, hi, disc in BAND_DISCIPLINE:
        if lo < cat_id <= hi:
            return disc
    return "general"


