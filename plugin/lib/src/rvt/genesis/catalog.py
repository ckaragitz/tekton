def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    from .types import IdSource
    if "--derive" in argv or not os.path.exists(ENUM_FILE):
        enum = derive_builtin_category_enum()
        os.makedirs(os.path.dirname(ENUM_FILE), exist_ok=True)
        with open(ENUM_FILE, "w") as fh:
            json.dump(enum, fh, indent=1)
        print(f"enum frozen -> {os.path.relpath(ENUM_FILE, ROOT)}: "
              f"{enum['count']} categories, {enum['cuttable']} cuttable")
    else:
        enum = load_builtin_category_enum()
        print(f"enum loaded: {enum['count']} categories, {enum['cuttable']} cuttable")
    if "--derive-profile" in argv or not os.path.exists(PROFILE_FILE):
        prof = derive_builtin_style_profile()
        os.makedirs(os.path.dirname(PROFILE_FILE), exist_ok=True)
        with open(PROFILE_FILE, "w") as fh:
            json.dump(prof, fh, indent=1)
        print(f"style profile frozen -> {os.path.relpath(PROFILE_FILE, ROOT)}: "
              f"{prof['count']} keys, summary {prof['summary']}")
    src = IdSource(2_000_000)
    recs = builtin_style_catalog(src, enum=enum)
    rep = catalog_report(recs)
    print(f"complete built-in style catalog: {rep['rows']} GStyleElem rows "
          f"(round-trip clean+byte-exact {rep['roundtrip_ok']}/{rep['rows']})")
    print("   by discipline:", rep["by_discipline"])
    print("   by style type:", rep["by_style_type"])
    for f in rep["failures"]:
        print("   FAIL", f)
    lint = lint_builtin_style_catalog(recs)
    print(f"   specimen lint: hard {len(lint['hard'])}, soft (document-wiring) "
          f"{len(lint['soft'])}, ok {lint['ok']}")
    return 0 if (rep["roundtrip_ok"] == rep["rows"] and lint["ok"]) else 1


if __name__ == "__main__":
    sys.exit(main())
