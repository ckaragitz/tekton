#!/usr/bin/env python3
"""Revit ``.rvt`` page-trailer ECC codec (CRACKED, wave 2 - ecc-writer-gate).

THE TRAILER = the parity of an I-way *bit-interleaved cyclic Hamming code*.

Every raw OLE stream is written as pages: 64,896 payload bytes followed by a
353-byte trailer (full page), or a shorter payload followed by a shorter
trailer (the final partial page).  Treat the page as ONE bit string, byte by
byte, **LSB-first inside each byte** (bit 0 of byte 0 comes first, exactly
like DEFLATE bit order) and read the first bit as the HIGHEST-degree
coefficient of a polynomial over GF(2).  Then::

    C(x) = M(x) * x^(8*F) + T(x)          M = payload(+pad zeros), T = trailer field
                                          F = trailer field length in bytes
    C(x) == 0  mod  g(x),  g(x) = h_m(x^I)

* ``h_m(y)`` is a *primitive polynomial of degree m* over GF(2) from the
  classic minimum-weight table (h4 = y^4+y+1, h5 = y^5+y^2+1, h7 = y^7+y+1,
  h11 = y^11+y^2+1 ...).
* ``I`` is the interleave depth; substituting x^I means the page bits are
  dealt round-robin into I sub-streams and each sub-stream is a codeword of
  the cyclic Hamming code generated by ``h_m`` (single-bit-error correcting
  per sub-stream => corrects any burst up to I bits per page).
* deg g = I*m parity bits.  Full 64,896-byte page: I=255, m=11,
  g(x) = x^2805 + x^510 + 1, 2,805 parity bits.
* Layout of the trailer field (F bytes): [pad_low zero bits][I*m parity
  bits][t_pad zero bits], t_pad = -(pad_low + I*m) mod 8.  Full page:
  pad_low = 12, parity 2805, t_pad = 7 -> exactly 353 bytes; bits 0..11 and
  2817..2823 of every full-page trailer are 0 and bits 12..2816 look uniform
  random (verified over 3,502 full pages).
* The parity is P(x) = ( M(x) * x^(pad_low + I*m) ) mod g(x) and the field
  polynomial is T(x) = P(x) * x^t_pad, i.e. parity coefficient e lives at
  field bit index (8*F - 1 - t_pad - e).

This module: parameter selection, encode, verify.  See docs/streams/09-page-ecc.md.
Run the built-in self test / demo::

    /Users/ck/dev/things/rev-revit/.venv/bin/python \
        /Users/ck/dev/things/rev-revit/experiments/ecc/ecc_codec.py
"""
from __future__ import annotations

import os
import sys
from typing import Dict, List, Optional, Sequence, Tuple

PAGE = 64896            # payload bytes per full page
TRAIL = 353             # trailer bytes per full page
STRIDE = PAGE + TRAIL   # 65249

# Bit-reversal table: our polynomial convention is LSB-first inside each byte,
# so reversing each byte's bits lets us run a plain MSB-first CRC engine.
_REV = bytes(int(f"{i:08b}"[::-1], 2) for i in range(256))

# Minimum-weight primitive polynomials over GF(2), degree -> exponent list.
# (The classic table; degrees actually observed in the corpus: 4,5,7,8,9,10,11.)
PRIM_STD: Dict[int, List[int]] = {
    2: [0, 1, 2],
    3: [0, 1, 3],
    4: [0, 1, 4],
    5: [0, 2, 5],
    6: [0, 1, 6],
    7: [0, 1, 7],
    8: [0, 2, 3, 4, 8],
    9: [0, 4, 9],
    10: [0, 3, 10],
    11: [0, 2, 11],
    12: [0, 1, 4, 6, 12],
    13: [0, 1, 3, 4, 13],
    14: [0, 1, 3, 5, 14],
    15: [0, 1, 15],
    16: [0, 2, 3, 5, 16],
    17: [0, 3, 17],
    18: [0, 7, 18],
    19: [0, 1, 2, 5, 19],
    20: [0, 3, 20],
}


def gpoly(I: int, m: int, exps: Optional[Sequence[int]] = None) -> int:
    """g(x) = h_m(x^I) as an integer (bit i = coefficient of x^i)."""
    exps = PRIM_STD[m] if exps is None else exps
    g = 0
    for e in exps:
        g |= 1 << (e * I)
    return g


def poly_from_stream(data: bytes) -> int:
    """Interpret ``data`` as a GF(2) polynomial: LSB-first bit stream, first
    bit = highest degree.  (Bit-reverse each byte, then big-endian int.)"""
    return int.from_bytes(data.translate(_REV), "big")


# --------------------------------------------------------------------------
# byte-table CRC engine for an arbitrary generator polynomial g
# --------------------------------------------------------------------------

class PolyCRC:
    """MSB-first (non-reflected) CRC-style register machine for generator g
    over GF(2).  Feeding the message bits (highest degree first) and reading
    the register yields (M(x) * x^deg) mod g(x)."""

    def __init__(self, g: int):
        self.g = g
        self.deg = g.bit_length() - 1
        assert self.deg >= 8
        self.mask = (1 << self.deg) - 1
        low = g ^ (1 << self.deg)          # g without its leading term
        # T[b] = (b(x) * x^deg) mod g   for b of degree < 8  ==  clmul(b, low)
        # valid because deg(low) + 7 < deg for all our sparse generators
        assert low.bit_length() + 7 <= self.deg
        tab = []
        for b in range(256):
            v = 0
            for k in range(8):
                if b >> k & 1:
                    v ^= low << k
            tab.append(v)
        self.tab = tab

    def rem(self, data: bytes, init: int = 0) -> int:
        """Feed ``data`` (a byte stream, LSB-first bits) into the register.
        Returns the register = (init(x)*x^(8n) + D(x) * x^deg) mod g."""
        r = init
        deg, mask, tab = self.deg, self.mask, self.tab
        sh = deg - 8
        for b in data.translate(_REV):
            top = ((r >> sh) ^ b) & 0xFF
            r = ((r << 8) & mask) ^ tab[top]
        return r

    def rem_bits(self, r: int, nbits: int) -> int:
        """Advance the register by ``nbits`` zero bits (multiply by x^nbits)."""
        deg, mask, tab = self.deg, self.mask, self.tab
        while nbits >= 8:
            top = (r >> (deg - 8)) & 0xFF
            r = ((r << 8) & mask) ^ tab[top]
            nbits -= 8
        for _ in range(nbits):
            r <<= 1
            if r >> deg:
                r ^= self.g
        return r


def codeword_ok(codeword: bytes, g: int) -> bool:
    """True iff the whole (payload || trailer field) bit string, read as a
    polynomial, is divisible by g."""
    return PolyCRC(g).rem(codeword) == 0


# --------------------------------------------------------------------------
# parameter selection (the writer's rule, reconstructed empirically)
# --------------------------------------------------------------------------

def hamming_len(m: int) -> int:
    """Full length of the Hamming code with m check bits = 2^m - 1."""
    return (1 << m) - 1


def select_params(nbits: int) -> Tuple[int, int]:
    """Return (I, m) for a page whose message is ``nbits`` bits long
    (payload bits incl. any zero pad the writer chose to place before the
    trailer).  See docs/streams/09-page-ecc.md section "Parameter selection".

    Rule (fits every observed page, full or final):
      * a per-interleave codeword may hold at most K_m = 2^m - 1 - m message
        bits (the Hamming code of order m);
      * the interleave depth is at least 65 and otherwise ceil(nbits / K_m);
      * m is the smallest order for which that depth does not exceed 255,
        EXCEPT that the minimum overall trailer wins between the two
        smallest feasible m ... [calibrated below]
    """
    # NOTE: implemented in select_params_table() from measured data; this
    # function encodes the fitted closed form.
    best = None
    for m in range(4, 21):
        K = hamming_len(m) - m
        I = max(65, -(-nbits // K))
        if I > 255:
            continue
        parity = I * m
        if best is None or parity < best[2]:
            best = (I, m, parity)
        break_ok = True
    if best is None:
        raise ValueError("message too long for one page")
    return best[0], best[1]


# --------------------------------------------------------------------------
# encode / decode helpers
# --------------------------------------------------------------------------

def trailer_field(payload: bytes, I: int, m: int, pad_low: int,
                  t_pad: Optional[int] = None,
                  exps: Optional[Sequence[int]] = None) -> bytes:
    """Compute the trailer field bytes for ``payload``.

    Field layout (bit index j, LSB-first within bytes, j=0 first):
      j in [0, pad_low)                       : 0
      j in [pad_low, pad_low + I*m)           : parity bits (highest degree first)
      j in [pad_low + I*m, 8*F)               : 0   (t_pad bits, default byte align)
    Parity polynomial: P = (payload(x) * x^(pad_low + I*m)) mod g(x).
    """
    g = gpoly(I, m, exps)
    r = I * m
    crc = PolyCRC(g)
    reg = crc.rem(payload)                 # payload(x) * x^r mod g   (r = deg)
    reg = crc.rem_bits(reg, pad_low)       # * x^pad_low
    if t_pad is None:
        t_pad = (-(pad_low + r)) % 8
    nfield = pad_low + r + t_pad
    assert nfield % 8 == 0
    F = nfield // 8
    # place parity coefficient e at field bit j = (nfield - 1 - t_pad - e)
    out = bytearray(F)
    for e in range(r):
        if reg >> e & 1:
            j = nfield - 1 - t_pad - e
            out[j >> 3] |= 1 << (j & 7)
    return bytes(out)


def full_page_trailer(page: bytes) -> bytes:
    """The 353-byte trailer of a full 64,896-byte page (I=255, m=11)."""
    assert len(page) == PAGE
    return trailer_field(page, 255, 11, pad_low=12, t_pad=7)


def repage(logical: bytes) -> bytes:
    """Re-frame a logical stream into pages with recomputed trailers.
    (Final-page trailer parameters via select_params on 8*len(final).)"""
    out = bytearray()
    pos = 0
    n = len(logical)
    while n - pos >= PAGE:
        page = logical[pos:pos + PAGE]
        out += page + full_page_trailer(page)
        pos += PAGE
    if pos < n:
        tail = logical[pos:]
        I, m = select_params(8 * len(tail))
        # pad_low: complete the message to a multiple of I bits ... (see docs)
        K = hamming_len(m) - m
        nmsg = 8 * len(tail)
        pad_low = I * (-(-nmsg // I)) - nmsg
        out += tail + trailer_field(tail, I, m, pad_low)
    return bytes(out)


def _selftest() -> int:
    """Verify the full-page code against real Revit pages."""
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ext = os.path.join(root, "extracted")
    files = sorted(d for d in os.listdir(ext) if os.path.isdir(os.path.join(ext, d)))
    n = ok = 0
    limit = int(os.environ.get("ECC_SELFTEST_PAGES", "60"))
    print(f"self-test: recomputing full-page trailers (I=255, m=11), up to {limit} pages/file")
    for f in files:
        for name in ("Global__Latest.bin", "Formats__Latest.bin", "Global__ContentDocuments.bin"):
            p = os.path.join(ext, f, name)
            if not os.path.exists(p):
                continue
            raw = open(p, "rb").read()
            k = 0
            while (k + 1) * STRIDE <= len(raw) and k < limit:
                page = raw[k * STRIDE:k * STRIDE + PAGE]
                tr = raw[k * STRIDE + PAGE:(k + 1) * STRIDE]
                mine = full_page_trailer(page)
                n += 1
                if mine == tr:
                    ok += 1
                else:
                    print(f"  MISMATCH {f}/{name} page {k}")
                k += 1
    print(f"full-page trailers reproduced byte-exact: {ok}/{n}")
    return 0 if ok == n and n > 0 else 1


if __name__ == "__main__":
    sys.exit(_selftest())
