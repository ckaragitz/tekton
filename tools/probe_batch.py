# control generation + staging
# ---------------------------------------------------------------------------
#: The genesis campaign consumed viewer rounds 1..14 before this gate existed
#: (docs/writer/verdict-integrity-audit.md); gated batches continue from 15
#: so a manifest number never collides with a historical round number.
HISTORICAL_ROUNDS = 14


#: Environment floor for batch numbers (#285): coord's `/batches k` reservation replies with a
#: range nobody else can be given; exporting its first number here makes EVERY stager that goes
#: through next_batch_number() honour it (most tools compute their own number and never see a
#: --batch flag). "highest local + 1" alone collides whenever two sessions branch from one main.
BATCH_FLOOR_ENV = "RVT_BATCH_FLOOR"


def next_batch_number(out_dir: str = ACCEPTANCE) -> int:
    n = HISTORICAL_ROUNDS
    for p in glob.glob(os.path.join(out_dir, "batch_*.json")):
        m = re.match(r"batch_(\d+)\.json$", os.path.basename(p))
        if m:
            n = max(n, int(m.group(1)))
    floor = os.environ.get(BATCH_FLOOR_ENV, "").strip()
    return max(n + 1, int(floor)) if floor.isdigit() else n + 1


def make_control(ledger: Ledger, batch_n: int, out_dir: str = ACCEPTANCE, *,
                 source: Optional[str] = None, release: Optional[int] = None) -> Entry:
    """Generate the batch's certified CONTROL: a byte-identical copy of a
    certified file, renamed CTRL_<stem>_b<n><ext> (the CTRL_ prefix + batch
    tag defeat the viewer's name/content dedupe; the BYTES are untouched, so
    the source's certification carries over exactly).

    Source: ``source`` if given, else the newest certified experiments/ file
    on disk, else (fresh clone) the pinned bundled composed base of
    ``release`` under plugin/assets/genesis/ -- admitted only because its
    sha256 proves it IS a ledger-certified file (Ledger.status alias rule)."""
    src = rel(source) if source else ledger.control_source(release)
    if not src:
        raise GateRefusal(["cannot generate a control: no certified file exists on disk "
                           "(ledger empty or every certified file missing, and no pinned "
                           "genesis base under plugin/assets/genesis/ hashes to a certified pin)"])
    st, entry = ledger.status(src)
    if st not in ("certified", "sample"):
        raise GateRefusal([f"control source {src} is not certified (status {st}) -- a control "
                           f"must be a byte-identical copy of a CERTIFIED file"])
    a = abspath(src)
    if not os.path.isfile(a):
        raise GateRefusal([f"control source {src} does not exist on disk"])
    stem, ext = os.path.splitext(os.path.basename(src))
    if stem.startswith(CONTROL_PREFIX):
        stem = stem[len(CONTROL_PREFIX):]
        stem = re.sub(r"_b\d+$", "", stem)
    name = f"{CONTROL_PREFIX}{stem}_b{batch_n}{ext or '.rvt'}"
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, name)
    shutil.copyfile(a, dst)
    src_md5 = md5_of(a)
    dst_md5 = md5_of(dst)
    if src_md5 != dst_md5:                                   # paranoia: the copy IS the point
        raise GateRefusal([f"control copy is not byte-identical to {src} ({dst_md5} != {src_md5})"])
    e = Entry(dst, "control")
    e.staged_as = rel(dst)
    e.md5 = dst_md5
    e.control_source = rel(src)
    e.base_status = st
    e.base_entry = entry
    return e


def stage_batch(probes: Sequence[str], *, candidate_bases: Sequence[str] = (),
                control_from: Optional[str] = None, out_dir: str = ACCEPTANCE,
                batch_n: Optional[int] = None, manifest_override: Optional[str] = None,
                copy: bool = True, ledger: Optional[Ledger] = None,
                note: str = "") -> dict:
    """Gate + control + stage + manifest.  Raises GateRefusal on violation.

    Writes <out_dir>/batch_<n>.json and copies every probe into out_dir
    (unless copy=False), returning the manifest dict.
    """
    ledger = ledger or Ledger.load()
    entries, violations = check_batch(probes, ledger, candidate_bases=candidate_bases,
                                      manifest_override=manifest_override)
    if violations:
        raise GateRefusal(violations)
    n = batch_n
    if not n:
        n = next_batch_number(out_dir)
        floor = os.environ.get(BATCH_FLOOR_ENV, "").strip()
        if floor and not floor.isdigit():
            print(f"warning: {BATCH_FLOOR_ENV}={floor!r} is not a number — ignored", file=sys.stderr)
        if not floor.isdigit():
            # "highest local + 1" is only right when nobody else is staging: two sessions branching
            # from the same main both took 57..59 (PRs #277/#283). coord's `/batches k` reply (#285)
            # is the collision-free source — pass it as --batch, or export it as RVT_BATCH_FLOOR.
            print(f"note: batch number {n} chosen locally (highest staged + 1). If other sessions may be "
                  f"staging too, reserve first — comment `/batches <k>` on your issue — and pass the "
                  f"number coord replies with as --batch (or export {BATCH_FLOOR_ENV}=<N>).", file=sys.stderr)
    control = make_control(ledger, n, out_dir, source=control_from,
                           release=batch_release(entries, ledger))
    os.makedirs(out_dir, exist_ok=True)
    ordered: List[Entry] = [control] + [e for e in entries if e.kind == "candidate-base"] + \
                           [e for e in entries if e.kind == "probe"]
    for i, e in enumerate(ordered):
        e.order = i
        if e.kind == "control":
            continue
        src = abspath(e.file)
        dst = os.path.join(out_dir, os.path.basename(e.file))
        if copy:
            if os.path.abspath(src) != os.path.abspath(dst):
                if os.path.exists(dst) and md5_of(dst) != e.md5:
                    raise GateRefusal([f"{e.file}: a DIFFERENT file already sits at {rel(dst)} "
                                       f"(md5 {md5_of(dst)} vs {e.md5}); rename the probe -- "
                                       f"never overwrite a staged file the viewer may already "
                                       f"have read"])
                shutil.copyfile(src, dst)
            e.staged_as = rel(dst)
        else:
            e.staged_as = rel(src)
    manifest = {
        "batch": n,
        "created": _dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "tool": "tools/probe_batch.py",
        "law": ("every entry's declared base is ITSELF in viewer-certified.json 'certified' "
                "(or is an Autodesk sample source); the batch carries >= 1 CONTROL = a "
                "byte-identical copy of a certified file; read the round with "
                "read_batch_verdicts(): control FAIL => every verdict VOID"),
        "ledger": rel(ledger.path),
        "control_count": 1,
        "note": note,
        "reading_order": [os.path.basename(e.staged_as or e.file) for e in ordered],
        "entries": [e.to_json() for e in ordered],
    }
    path = os.path.join(out_dir, f"batch_{n}.json")
    with open(path, "w") as fh:
        json.dump(manifest, fh, indent=1)
    manifest["manifest_path"] = rel(path)
    return manifest


