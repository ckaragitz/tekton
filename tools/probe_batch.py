def classify_history(rounds: Sequence[dict] = HISTORY_ROUNDS) -> List[dict]:
    """Replay every recorded genesis verdict through the standing-controls
    rules and classify it:

      SOUND      base certified at (or PASS-co-uploaded in) verdict time AND the
                 round carried >= 1 known-PASS file (a passing certified copy,
                 or a co-uploaded file that PASSED -- historically the only
                 controls there were).
      UNGUARDED  base was fine but the round carried NO passing control: the
                 verdict is probably real but the round could not prove the
                 oracle healthy (retro-confirmed by the ~01:55 CTRL passes).
      VOID       the base was NEVER certified, or had ITSELF failed: the
                 verdict is an artefact candidate, not evidence.
    A PASS is self-certifying and reads SURVIVES.  This is exactly
    read_batch_verdicts() applied to history: control-then-base-then-probe.
    """
    # certification timeline: file -> round when its PASS was recorded
    certified_at: Dict[str, int] = {p: 0 for p in HISTORY_PREGENESIS_CERTIFIED}
    failed_at: Dict[str, int] = {}
    # pre-scan: when did each file eventually FAIL (to annotate 'NEVER certified' bases)
    fails_eventual: Dict[str, int] = {}
    for r in rounds:
        for u in r["uploads"]:
            if normalise_verdict(u["verdict"]) == "FAIL":
                fails_eventual.setdefault(rel(u["file"]), r["round"])
    rows: List[dict] = []
    for r in rounds:
        rn = r["round"]
        ups = r["uploads"]
        # a round is GUARDED if any upload in it PASSED (co-uploaded candidates
        # were the only 'controls' before round 12) -- passes are computed in
        # the same loop so a same-round PASS guards its neighbours.
        passers = [u["file"] for u in ups if normalise_verdict(u["verdict"]) == "PASS"]
        guarded = bool(passers)
        deliberate = [u["file"] for u in ups if u.get("kind") == "control"
                      and normalise_verdict(u["verdict"]) == "PASS"]
        # register this round's passes first so same-round co-uploads count
        for u in ups:
            if normalise_verdict(u["verdict"]) == "PASS":
                certified_at.setdefault(rel(u["file"]), rn)
        for u in ups:
            f = rel(u["file"])
            v = normalise_verdict(u["verdict"])
            base_desc = u.get("base") or ""
            base_file = _basefile(base_desc)
            base_rel = rel(base_file) if base_file else None
            row: Dict[str, Any] = {"round": rn, "when": r["when"], "file": f, "verdict": v,
                                   "base": base_rel or base_desc,
                                   "recorded_cause": u.get("recorded_cause"),
                                   "later": u.get("later")}
            if v == "PASS":
                row["class"] = "SURVIVES"
                row["reason"] = ("a PASS is self-certifying" +
                                 (" (deliberate certified control)" if u.get("kind") == "control" else ""))
                rows.append(row)
                continue
            # base status AT THIS ROUND
            if base_rel is None:
                bstat = "undeclared"
            elif base_rel.startswith("samples/"):
                bstat = "sample-source (certified by definition)"
            elif base_rel in failed_at and failed_at[base_rel] <= rn:
                bstat = f"FAILED (round {failed_at[base_rel]})"
            elif base_rel in certified_at and certified_at[base_rel] <= rn:
                bstat = ("certified" if certified_at[base_rel] < rn
                         else "certified this round (co-uploaded PASS)")
            elif base_rel in certified_at:
                bstat = f"certified LATER (round {certified_at[base_rel]})"
            elif base_rel in fails_eventual:
                bstat = f"NEVER certified (itself FAILED later, round {fails_eventual[base_rel]})"
            else:
                bstat = "NEVER certified"
            row["base_status_at_verdict"] = bstat
            row["round_guarded"] = guarded
            row["round_control"] = ("deliberate certified control passed" if deliberate else
                                    ("co-uploaded file(s) PASSED: " + ", ".join(os.path.basename(p) for p in passers))
                                    if guarded else "NONE -- no known-PASS file in the round")
            if bstat.startswith("NEVER") or bstat.startswith("FAILED") or bstat == "undeclared":
                row["class"] = "VOID"
                row["reason"] = f"base {row['base']}: {bstat}"
            elif bstat.startswith("certified LATER"):
                row["class"] = "VOID"
                row["reason"] = f"base {row['base']} was not yet certified at verdict time ({bstat})"
            elif not guarded:
                row["class"] = "UNGUARDED"
                row["reason"] = ("base sound but the round carried NO passing control; oracle "
                                 "health for the window rests on other rounds")
            else:
                row["class"] = "SOUND"
                row["reason"] = f"base {row['base']} {bstat}; {row['round_control']}"
            failed_at.setdefault(f, rn)
            rows.append(row)
    return rows


def render_history(rows: Sequence[dict]) -> str:
    """Markdown table of the retro classification."""
    lines = ["| # | round | file | verdict | base (status at verdict) | control in round | CLASS |",
             "|--:|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        base = r.get("base") or ""
        bstat = r.get("base_status_at_verdict", "")
        ctrl = r.get("round_control", "")
        f = os.path.basename(r["file"])
        lines.append(f"| {i} | {r['round']} | `{f}` | {r['verdict']} | "
                     f"`{os.path.basename(str(base)) or base}` {bstat} | {ctrl} | **{r['class']}** |")
    return "\n".join(lines)


def history_summary(rows: Sequence[dict], rounds: Sequence[dict] = HISTORY_ROUNDS) -> dict:
    from collections import Counter
    c = Counter(r["class"] for r in rows)
    fails = [r for r in rows if r["verdict"] == "FAIL"]
    fc = Counter(r["class"] for r in fails)
    passes_by_round = {r["round"]: [os.path.basename(u["file"]) for u in r["uploads"]
                                   if normalise_verdict(u["verdict"]) == "PASS"]
                       for r in rounds}
    deliberate_by_round = {r["round"]: [os.path.basename(u["file"]) for u in r["uploads"]
                                       if u.get("kind") == "control" and
                                       normalise_verdict(u["verdict"]) == "PASS"]
                           for r in rounds}
    fail_rounds = sorted({r["round"] for r in fails})
    return {"verdicts": len(rows), "by_class": dict(c),
            "fails": len(fails), "fails_by_class": dict(fc),
            "rounds": len(rounds),
            "rounds_with_any_pass": sorted(k for k, v in passes_by_round.items() if v),
            "rounds_with_deliberate_certified_control":
                sorted(k for k, v in deliberate_by_round.items() if v),
            "fail_rounds_with_no_pass":
                [k for k in fail_rounds if not passes_by_round.get(k)]}


