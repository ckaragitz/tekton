def rel(path: str) -> str:
    """Repo-relative POSIX path (ledger / manifest paths are repo-relative);
    a path outside the repo stays absolute."""
    a = os.path.abspath(os.path.join(ROOT, path))
    try:
        r = os.path.relpath(a, ROOT)
    except ValueError:
        return a
    if r.startswith(".."):
        return a
    return r.replace(os.sep, "/")


def abspath(path: str) -> str:
    return path if os.path.isabs(path) else os.path.join(ROOT, path)


def _digest(path: str, algo: str) -> str:
    h = hashlib.new(algo)
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def md5_of(path: str) -> str:
    return _digest(path, "md5")


def sha256_of(path: str) -> str:
    return _digest(path, "sha256")


