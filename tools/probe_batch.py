class Entry:
    """One file admitted to a batch."""

    def __init__(self, file: str, kind: str, base: Optional[BaseResolution] = None):
        self.file = rel(file)
        self.kind = kind                     # 'control' | 'candidate-base' | 'probe'
        self.base = base
        self.base_status: str = "n/a"
        self.base_entry: Optional[dict] = None
        self.control_source: Optional[str] = None
        self.staged_as: Optional[str] = None
        self.md5: Optional[str] = None
        self.order: int = 0
        self.advisory: Optional[str] = None

    def to_json(self) -> dict:
        d: Dict[str, Any] = {
            "order": self.order,
            "file": self.file,
            "staged_as": self.staged_as,
            "md5": self.md5,
            "kind": self.kind,
            "control": self.kind == "control",
        }
        if self.kind == "control":
            d["control_source"] = self.control_source
            d["base"] = self.control_source
            d["base_certification"] = (self.base_entry or {}).get("proves")
            if (self.base_entry or {}).get("aliased_from"):        # cut from a pinned copy: name
                d["control_certified_as"] = self.base_entry.get("file")   # the ledger entry it IS
                d["control_sha256"] = self.base_entry.get("alias_sha256")
        else:
            d["base"] = self.base.base if self.base else None
            d["base_declared_by"] = self.base.source if self.base else None
            d["base_status"] = self.base_status
            d["base_certification"] = (self.base_entry or {}).get("proves") if self.base_entry else None
            if (self.base_entry or {}).get("aliased_from"):
                d["base_certified_as"] = self.base_entry.get("file")
        if self.advisory:
            d["advisory"] = self.advisory
        return d


def gate_probe(probe: str, ledger: Ledger, kind: str = "probe",
               manifest_override: Optional[str] = None) -> Tuple[Entry, List[str]]:
    """Resolve one probe's base and return (Entry, violations)."""
    e = Entry(probe, kind)
    v: List[str] = []
    a = abspath(e.file)
    if not os.path.isfile(a):
        v.append(f"{e.file}: file does not exist")
        return e, v
    e.md5 = md5_of(a)
    if kind == "candidate-base":
        # A file uploaded FOR certification: no certified base required, but
        # record whatever lineage its manifest declares (informational) and
        # WARN (not refuse) when that lineage is itself a recorded failure --
        # the candidate very likely inherits the defect (K2 <- K1).
        e.base = resolve_base(e.file, manifest_override, ledger.pins)
        st, entry = ledger.status(e.base.base) if e.base.base else ("undeclared", None)
        e.base_status = f"{st} (lineage informational only for a candidate-base)"
        e.base_entry = entry
        if st == "failed":
            e.advisory = (f"declared lineage {e.base.base} is a RECORDED FAILURE -- this candidate "
                          f"almost certainly inherits its defect; prefer rebuilding it on a "
                          f"certified base")
        return e, v
    e.base = resolve_base(e.file, manifest_override, ledger.pins)
    if not e.base.base:
        v.append(f"PROBE {e.file}: NO DECLARED BASE -- {e.base.source}. Every probe must "
                 f"declare its base in a probes.json (fields {list(BASE_KEYS)}) or sit next to "
                 f"the front-door manifest.json that built it; undeclared "
                 f"lineage is refused (that is how the K1 base slipped through).")
        e.base_status = "undeclared"
        return e, v
    st, entry = ledger.status(e.base.base)
    e.base_status = st
    e.base_entry = entry
    if st == "certified":
        pass
    elif st == "sample":
        pass
    elif st == "failed":
        v.append(f"PROBE {e.file}: declared BASE {e.base.base} (from {e.base.source}) is a "
                 f"RECORDED VIEWER FAILURE in the ledger ({(entry or {}).get('verdict', 'FAILED')}"
                 f", {(entry or {}).get('when', 'time n/a')}). A probe on a FAILED base tests "
                 f"nothing: rebase it on a certified file, or upload the fixed base as a "
                 f"candidate-base first.")
    else:
        v.append(f"PROBE {e.file}: declared BASE {e.base.base} (from {e.base.source}) is NOT "
                 f"in docs/coverage/viewer-certified.json 'certified'. 'Derived from a certified "
                 f"file' does not count and the manifest's own '(viewer PASS)' prose is not "
                 f"evidence -- the base must ITSELF be viewer-certified before anything is built "
                 f"on it. Upload {e.base.base} as a candidate-base first (with a control), certify "
                 f"it, then re-propose this probe.")
    return e, v


def check_batch(probes: Sequence[str], ledger: Optional[Ledger] = None, *,
                candidate_bases: Sequence[str] = (),
                manifest_override: Optional[str] = None) -> Tuple[List[Entry], List[str]]:
    """Gate a proposed batch WITHOUT staging.  Returns (entries, violations).
    An empty violation list means the batch is admissible (a control is added
    at stage time)."""
    ledger = ledger or Ledger.load()
    entries: List[Entry] = []
    violations: List[str] = []
    seen: Dict[str, str] = {}
    for kind, files in (("candidate-base", candidate_bases), ("probe", probes)):
        for f in files:
            e, v = gate_probe(f, ledger, kind=kind, manifest_override=manifest_override)
            entries.append(e)
            violations.extend(v)
            bn = os.path.basename(e.file)
            if bn in seen and seen[bn] != e.file:
                violations.append(f"{e.file}: BASENAME COLLISION with {seen[bn]} -- the viewer "
                                  f"and the acceptance folder key on the file NAME; rename one.")
            seen[bn] = e.file
    if not probes and not candidate_bases:
        violations.append("empty batch: nothing to gate")
    return entries, violations


def batch_release(entries: Sequence[Entry], ledger: Ledger) -> Optional[int]:
    """The ONE Revit release the batch's probes declare (so a fresh-clone
    control is cut from the same release's composed base): the release the
    declaring manifest names, else the genesis pin the declared base IS.
    None when nothing names a release or the probes disagree."""
    years = set()
    for e in entries:
        if not (e.base and e.base.base):
            continue
        pin = ledger.pin_for(e.base.base)
        year = e.base.release or (pin.release if pin else None)
        if year:
            years.add(int(year))
    return years.pop() if len(years) == 1 else None


