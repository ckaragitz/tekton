# verdict interpretation -- the ONLY safe reading order
# ---------------------------------------------------------------------------
def normalise_verdict(v: Any) -> str:
    """Map a raw viewer verdict to PASS / FAIL / PENDING."""
    if v is None:
        return "PENDING"
    if isinstance(v, bool):
        return "PASS" if v else "FAIL"
    s = str(v).strip().upper()
    if not s or s in ("PENDING", "QUEUED", "UNKNOWN", "?", "NONE", "NULL"):
        return "PENDING"
    if s in _VERDICT_PASS or s.startswith("PASS"):
        return "PASS"
    if any(tok in s for tok in _VERDICT_FAIL_TOKENS):
        return "FAIL"
    return "PENDING"


def _match_verdict(entry: dict, verdicts: Dict[str, Any]) -> Any:
    """Find the verdict for a manifest entry: by staged path, source path,
    basename, or stem."""
    keys = []
    for k in (entry.get("staged_as"), entry.get("file")):
        if k:
            keys += [k, os.path.basename(k), os.path.splitext(os.path.basename(k))[0]]
    for k in keys:
        if k in verdicts:
            return verdicts[k]
    return None


def read_batch_verdicts(manifest: dict, verdicts: Dict[str, Any],
                        ledger: Optional[Ledger] = None) -> dict:
    """INTERPRET a round.  The order below is the whole point:

      1. CONTROL first.  Any control FAIL => the ORACLE / ENVIRONMENT is
         suspect (or the upload deduped/staled): every other verdict in the
         round is VOID -- nothing is attributed, nothing enters the ledger.
         Control PENDING/missing => the round is INCOMPLETE: interpret nothing
         until the control reads.  (A round with zero controls is refused
         outright -- it was never a legal batch.)
      2. Each probe's base is RE-CHECKED against the current ledger.  A base
         that has never been certified => refuse to interpret THAT probe and
         demand the base be uploaded (as a candidate-base) first: on an
         uncertified base a FAIL cannot be attributed to the probe's change.
      3. Only then: a probe FAIL is attributed to the probe's ONE change vs
         its certified base; a probe/candidate-base PASS is a certification.
    Returns a structured interpretation incl. suggested ledger updates.
    """
    ledger = ledger or Ledger.load()
    entries = list(manifest.get("entries") or [])
    controls = [e for e in entries if e.get("control") or e.get("kind") == "control"]
    others = [e for e in entries if not (e.get("control") or e.get("kind") == "control")]
    out: Dict[str, Any] = {
        "batch": manifest.get("batch"),
        "manifest": manifest.get("manifest_path"),
        "status": None,
        "message": "",
        "control_results": [],
        "per_file": [],
        "ledger_updates": {"certified": [], "failed": []},
        "actions": [],
    }
    if not controls:
        out["status"] = "REFUSED_NO_CONTROL"
        out["message"] = ("the round carried NO certified control: it can prove nothing about "
                          "the oracle, so no verdict in it is interpretable. This is the four-round "
                          "failure of 2026-08-04. Re-upload with a CTRL_ copy (probe_batch.py stage).")
        out["actions"].append("re-stage the same files through the gate; it adds the control")
        for e in others:
            raw = _match_verdict(e, verdicts)
            out["per_file"].append({"file": e.get("file"), "kind": e.get("kind"),
                                    "raw_verdict": raw, "reading": "UNGUARDED -- round has no "
                                    "control; do not attribute"})
        return out
    # ---- 1. controls -------------------------------------------------------
    ctrl_pending = ctrl_fail = 0
    for c in controls:
        raw = _match_verdict(c, verdicts)
        norm = normalise_verdict(raw)
        out["control_results"].append({"file": c.get("staged_as") or c.get("file"),
                                       "source": c.get("control_source"),
                                       "raw_verdict": raw, "verdict": norm})
        if norm == "FAIL":
            ctrl_fail += 1
        elif norm == "PENDING":
            ctrl_pending += 1
    if ctrl_fail:
        out["status"] = "VOID_ROUND"
        out["message"] = ("A CERTIFIED CONTROL FAILED (a byte-identical copy of a viewer-PASSED "
                          "file did not pass). This is an ORACLE / ENVIRONMENT problem -- service "
                          "degradation, throttling, a stale/deduped read, or an upload fault -- NOT "
                          "a finding about any file. EVERY OTHER VERDICT IN THIS ROUND IS VOID. "
                          "Pause the loop; re-upload a fresh control ALONE; interpret nothing until "
                          "a control passes; then re-upload this round's files.")
        out["actions"] += ["pause probe uploads",
                           "upload a fresh certified control ALONE and wait for its PASS",
                           "re-upload every file of this round in a new batch (new manifest)",
                           "do NOT enter any of this round's verdicts into the ledger"]
        for e in others:
            out["per_file"].append({"file": e.get("file"), "kind": e.get("kind"),
                                    "raw_verdict": _match_verdict(e, verdicts),
                                    "reading": "VOID -- control failed; the round did not measure"})
        return out
    if ctrl_pending:
        out["status"] = "INCOMPLETE"
        out["message"] = ("the control has not read out yet: interpret NOTHING in this round until "
                          "the control's verdict arrives (the control is read FIRST, always)")
        out["actions"].append("wait for the control verdict; re-run read_batch_verdicts")
        for e in others:
            out["per_file"].append({"file": e.get("file"), "kind": e.get("kind"),
                                    "raw_verdict": _match_verdict(e, verdicts),
                                    "reading": "PENDING -- awaiting control"})
        return out
    # ---- 2. + 3. probes / candidate-bases ----------------------------------
    refused = attributed = pending = 0
    for e in others:
        raw = _match_verdict(e, verdicts)
        norm = normalise_verdict(raw)
        rec: Dict[str, Any] = {"file": e.get("file"), "kind": e.get("kind"),
                               "raw_verdict": raw, "verdict": norm}
        kind = e.get("kind")
        if kind == "candidate-base":
            if norm == "PASS":
                rec["reading"] = "CERTIFIED (candidate-base PASS): add to 'certified'; probes may now build on it"
                out["ledger_updates"]["certified"].append(
                    {"file": e.get("file"),
                     "proves": "viewer PASS as a candidate BASE (batch %s, control passed)" % manifest.get("batch")})
                attributed += 1
            elif norm == "FAIL":
                rec["reading"] = ("CANDIDATE BASE FAILS on its own: record in 'failed'; NOTHING may be "
                                  "built on it and anything already derived from it is VOID; bisect "
                                  "its construction (its own base is: %s)" % e.get("base"))
                out["ledger_updates"]["failed"].append(
                    {"file": e.get("file"), "verdict": "PROCESSING FAILED",
                     "note": "candidate BASE failed in batch %s with the control PASSING -- a real "
                             "defect of the file itself; every probe built on it is VOID" % manifest.get("batch")})
                attributed += 1
            else:
                rec["reading"] = "PENDING"
                pending += 1
            out["per_file"].append(rec)
            continue
        # probe: re-check the base NOW (the ledger is the authority, and it may have moved)
        base = e.get("base")
        st, _entry = ledger.status(base) if base else ("undeclared", None)
        rec["base"] = base
        rec["base_status_now"] = st
        if norm == "PENDING":
            rec["reading"] = "PENDING"
            pending += 1
            out["per_file"].append(rec)
            continue
        if st not in ("certified", "sample"):
            rec["reading"] = ("REFUSED -- the probe's own BASE %s has never been certified (status: "
                              "%s). A %s on an uncertified base is not attributable to the probe's "
                              "change. Upload %s as a candidate-base with a control, certify it, then "
                              "re-read." % (base, st, norm, base))
            out["actions"].append("upload the base %s as a candidate-base first" % base)
            refused += 1
            out["per_file"].append(rec)
            continue
        if norm == "PASS":
            rec["reading"] = ("PASS on a certified base with the control passing: the file is "
                              "certifiable; its ONE change vs %s is reader-accepted" % base)
            out["ledger_updates"]["certified"].append(
                {"file": e.get("file"),
                 "proves": "viewer PASS (batch %s; base %s certified; control passed)"
                           % (manifest.get("batch"), base)})
        else:
            rec["reading"] = ("ATTRIBUTED FAIL: base %s is certified and the control passed, so this "
                              "FAIL is REAL evidence and it convicts the probe's ONE stated change "
                              "vs that base. Read the card message; bisect that change." % base)
            out["ledger_updates"]["failed"].append(
                {"file": e.get("file"), "verdict": "PROCESSING FAILED",
                 "note": "SOUND finding (batch %s: base %s certified, control passed) -- attributable "
                         "to the probe's single change vs its base" % (manifest.get("batch"), base)})
        attributed += 1
        out["per_file"].append(rec)
    if refused and not attributed:
        out["status"] = "REFUSED_UNCERTIFIED_BASE"
        out["message"] = ("the control PASSED (oracle healthy) but the probes' own BASE(S) have never "
                          "been certified: no failure is attributable. Upload the base(s) first.")
    elif refused:
        out["status"] = "INTERPRETED_PARTIAL"
        out["message"] = ("control PASSED; %d verdict(s) attributed; %d refused (uncertified base); "
                          "%d pending" % (attributed, refused, pending))
    elif pending and not attributed:
        out["status"] = "INCOMPLETE"
        out["message"] = "control PASSED; probe verdicts pending"
    else:
        out["status"] = "INTERPRETED"
        out["message"] = ("control PASSED (oracle healthy): %d verdict(s) attributed; %d pending"
                          % (attributed, pending))
    return out


