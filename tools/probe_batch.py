def _parse_verdict_args(pairs: Sequence[str], json_path: Optional[str]) -> Dict[str, str]:
    out: Dict[str, str] = {}
    if json_path:
        with open(abspath(json_path)) as fh:
            data = json.load(fh)
        if isinstance(data, dict):
            for k, v in data.items():
                out[str(k)] = v if isinstance(v, str) else json.dumps(v)
        elif isinstance(data, list):
            for e in data:
                if isinstance(e, dict) and e.get("file"):
                    out[str(e["file"])] = str(e.get("verdict", "PENDING"))
    for p in pairs:
        if "=" not in p:
            raise SystemExit(f"--verdict expects FILE=PASS|FAIL, got {p!r}")
        k, v = p.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    sc = sub.add_parser("check", help="dry-run the gate: print violations, stage nothing")
    sc.add_argument("files", nargs="*")
    sc.add_argument("--candidate-base", action="append", default=[],
                    help="file uploaded FOR certification (exempt from the certified-base rule)")
    sc.add_argument("--manifest", default=None, help="probes.json to resolve bases from")
    sc.add_argument("--json", action="store_true")

    ss = sub.add_parser("stage", help="gate + certified control + stage into experiments/acceptance/")
    ss.add_argument("files", nargs="*")
    ss.add_argument("--candidate-base", action="append", default=[])
    ss.add_argument("--control-from", default=None,
                    help="certified file to copy as the control (default: newest certified on disk)")
    ss.add_argument("--manifest", default=None)
    ss.add_argument("--batch", type=int, default=None, help="batch number (default: next)")
    ss.add_argument("--out-dir", default=ACCEPTANCE)
    ss.add_argument("--note", default="")
    ss.add_argument("--no-copy", action="store_true", help="write the manifest but do not copy probes")
    ss.add_argument("--json", action="store_true")

    sr = sub.add_parser("resolve", help="print each file's resolved base + ledger status")
    sr.add_argument("files", nargs="+")
    sr.add_argument("--manifest", default=None)

    sv = sub.add_parser("verdicts", help="interpret a round from its batch_<n>.json + verdicts")
    sv.add_argument("batch_json")
    sv.add_argument("--verdict", action="append", default=[], help="FILE=PASS|FAIL (repeatable)")
    sv.add_argument("--verdicts-json", default=None, help="{file: verdict} JSON")
    sv.add_argument("--json", action="store_true")

    sh = sub.add_parser("retro", help="replay the recorded history through the same rules")
    sh.add_argument("--json", action="store_true")

    args = ap.parse_args(argv)

    if args.cmd in ("check", "stage"):
        ledger = Ledger.load()
        if args.cmd == "check":
            entries, violations = check_batch(args.files, ledger,
                                              candidate_bases=args.candidate_base,
                                              manifest_override=args.manifest)
            if args.json:
                print(json.dumps({"entries": [e.to_json() for e in entries],
                                  "violations": violations,
                                  "admissible": not violations}, indent=1))
            else:
                for e in entries:
                    b = e.base.base if e.base else None
                    st = e.base_status
                    if (e.base_entry or {}).get("aliased_from"):
                        st += f"; certified as {e.base_entry.get('file')} by sha256"
                    elif e.base and e.base.digest_matched:
                        st += "; pinned base recognised by sha256"
                    print(f"  {e.kind:14s} {e.file}\n"
                          f"      base = {b}  [{st}]"
                          + (f"\n      declared by {e.base.source}" if e.base else ""))
                ctrl = ledger.control_source(batch_release(entries, ledger)) or "NONE AVAILABLE"
                if violations:
                    print("\nBATCH REFUSED -- %d violation(s):" % len(violations))
                    for v in violations:
                        print("  * " + v)
                    print("\n(the gate would also add 1 certified control: %s)" % ctrl)
                else:
                    print("\nADMISSIBLE -- `stage` will add the certified control "
                          "(source: %s) and write the manifest" % ctrl)
            return 0 if not violations else 2
        try:
            man = stage_batch(args.files, candidate_bases=args.candidate_base,
                              control_from=args.control_from, out_dir=args.out_dir,
                              batch_n=args.batch, manifest_override=args.manifest,
                              copy=not args.no_copy, ledger=ledger, note=args.note)
        except GateRefusal as gr:
            print(str(gr), file=sys.stderr)
            return 2
        if args.json:
            print(json.dumps(man, indent=1))
        else:
            print(f"batch {man['batch']} staged -> {man['manifest_path']}")
            print("reading order (control FIRST):")
            for e in man["entries"]:
                extra = (f"copy of {e.get('control_source')}" if e["kind"] == "control"
                         else f"base={e.get('base')} [{e.get('base_status', 'candidate')}]")
                print(f"  {e['order']}. {e['kind']:14s} {e['file']}  {extra}")
                if e.get("advisory"):
                    print(f"       ADVISORY: {e['advisory']}")
        return 0

    if args.cmd == "resolve":
        ledger = Ledger.load()
        for f in args.files:
            br = resolve_base(f, args.manifest, ledger.pins)
            st, entry = ledger.status(br.base) if br.base else ("undeclared", None)
            print(json.dumps({**br.to_json(), "ledger_status": st,
                              "ledger_entry": entry}, indent=1))
        return 0

    if args.cmd == "verdicts":
        with open(abspath(args.batch_json)) as fh:
            man = json.load(fh)
        man.setdefault("manifest_path", rel(args.batch_json))
        verdicts = _parse_verdict_args(args.verdict, args.verdicts_json)
        res = read_batch_verdicts(man, verdicts)
        outp = os.path.splitext(abspath(args.batch_json))[0] + ".verdicts.json"
        with open(outp, "w") as fh:
            json.dump({"input_verdicts": verdicts, "interpretation": res}, fh, indent=1)
        if args.json:
            print(json.dumps(res, indent=1))
        else:
            print(f"round status: {res['status']}\n{res['message']}\n")
            for c in res["control_results"]:
                print(f"  CONTROL {c['file']}: {c['verdict']}")
            for p in res["per_file"]:
                print(f"  {p.get('kind', '?'):14s} {p['file']}: {p.get('reading')}")
            if res["actions"]:
                print("actions:\n  - " + "\n  - ".join(res["actions"]))
            print(f"\n(written {rel(outp)})")
        return 0

    if args.cmd == "retro":
        rows = classify_history()
        if args.json:
            print(json.dumps({"rows": rows, "summary": history_summary(rows)}, indent=1))
        else:
            print(render_history(rows))
            print()
            print(json.dumps(history_summary(rows), indent=1))
        return 0
    return 1


if __name__ == "__main__":
    sys.exit(main())
