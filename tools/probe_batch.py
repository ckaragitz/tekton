# ---------------------------------------------------------------------------
# the genesis pins (rvt.frontdoor.base GenesisPin, read-only) -- where the
# certified composed bases live on a fresh clone, and under which sha256
# ---------------------------------------------------------------------------
class PinnedBase:
    """One GenesisPin release slot: the certified composed base of one Revit
    release, its pinned sha256, and every path a byte-identical copy of it
    may sit at (the experiments/ compose output, plugin/assets/genesis/, a
    plugin bundle).  The ledger decides whether ``relpath`` is certified;
    the pin only says which BYTES that path holds."""

    def __init__(self, release: int, relpath: str, sha256: str,
                 candidates: Sequence[str] = ()):
        self.release = int(release)
        self.relpath = rel(relpath)
        self.sha256 = str(sha256).lower()
        self.candidates = [abspath(c) for c in candidates] or [abspath(self.relpath)]


def genesis_pins() -> List[PinnedBase]:
    """The release slots of the shipped genesis pin (src/rvt/frontdoor/assets/
    genesis_base.json via rvt.frontdoor.base.PIN), newest release first.
    Empty when the engine is not importable from this script's root (the
    gate then behaves exactly as before: ledger paths only)."""
    for p in (os.path.join(ROOT, "src"), os.path.join(ROOT, "lib", "src")):   # repo / plugin layout
        if os.path.isdir(p) and p not in sys.path:
            sys.path.insert(0, p)
    try:
        from rvt.frontdoor.base import PIN
    except Exception:                                        # engine absent: no pins, old rules
        return []
    pins: List[PinnedBase] = []
    for year in sorted(PIN.release_years(), reverse=True):
        slot = PIN.release_slot(year) or {}
        rp, sha = slot.get("relpath"), slot.get("sha256")
        if not rp or not sha:                                # a pending slot pins nothing
            continue
        pins.append(PinnedBase(year, str(rp), str(sha),
                               PIN.candidate_paths(relpath=str(rp))))
    return pins


# ---------------------------------------------------------------------------
# the ledger (docs/coverage/viewer-certified.json) -- the ONLY authority
# ---------------------------------------------------------------------------
class Ledger:
    """The orchestrator's viewer-certified ledger.

    ``certified`` and ``failed`` map repo-relative file paths to their entry.
    A file's certification is decided HERE and nowhere else: a probes.json
    saying "(viewer PASS)" about its base is prose, not evidence.

    ``pins`` are the genesis release slots (see PinnedBase): they let a file
    on ANY path read as a certified entry when its sha256 proves it IS that
    entry's bytes (the alias rule in the module docstring).
    """

    def __init__(self, certified: Dict[str, dict], failed: Dict[str, dict],
                 path: str = LEDGER, pins: Optional[Sequence[PinnedBase]] = None):
        self.certified = certified
        self.failed = failed
        self.path = path
        self.pins: List[PinnedBase] = list(genesis_pins() if pins is None else pins)
        self._sha_cache: Dict[str, str] = {}                 # abs path -> sha256 (hash each file once)
        # sha256 -> certified repo path: every certified entry that records its
        # own 'sha256', plus every genesis pin whose pinned relpath is ITSELF
        # in 'certified' (the pin supplies the digest the older ledger entries
        # lack; the ledger still supplies the certification)
        self.sha_index: Dict[str, str] = {}
        for p, e in certified.items():
            if e.get("sha256"):
                self.sha_index.setdefault(str(e["sha256"]).lower(), p)
        for pin in self.pins:
            if pin.relpath in certified:
                self.sha_index.setdefault(pin.sha256, pin.relpath)

    @classmethod
    def load(cls, path: str = LEDGER, pins: Optional[Sequence[PinnedBase]] = None) -> "Ledger":
        if not os.path.exists(path):
            return cls({}, {}, path, pins)
        with open(path) as fh:
            data = json.load(fh)
        cert = {rel(e["file"]): e for e in (data.get("certified") or []) if e.get("file")}
        fail = {rel(e["file"]): e for e in (data.get("failed") or []) if e.get("file")}
        return cls(cert, fail, path, pins)

    # -- the sha256 alias rule ------------------------------------------------
    def _sha256(self, relpath: str) -> Optional[str]:
        a = os.path.abspath(abspath(relpath))
        if not os.path.isfile(a):
            return None
        if a not in self._sha_cache:
            self._sha_cache[a] = sha256_of(a).lower()
        return self._sha_cache[a]

    def alias(self, relpath: str) -> Optional[Tuple[str, str]]:
        """(certified_path, sha256) when the file at ``relpath`` is byte-for-
        byte a certified entry (see sha_index), else None."""
        digest = self._sha256(relpath)
        hit = self.sha_index.get(digest) if digest else None
        return (hit, digest) if hit else None

    def pin_for(self, relpath: Optional[str]) -> Optional[PinnedBase]:
        """The genesis pin whose certified relpath IS ``relpath`` (so the
        gate knows a base's release without opening it)."""
        p = rel(relpath) if relpath else None
        return next((pin for pin in self.pins if pin.relpath == p), None)

    def pinned_certified_on_disk(self, release: Optional[int] = None) -> Optional[str]:
        """A pinned composed base that is on disk, hashes to its pin AND whose
        pinned relpath is ledger-certified -- the fresh-clone control source.
        ``release`` picks that release's slot; None = newest release first.
        A candidate copy that fails its pin's digest is not that base."""
        for pin in self.pins:
            if release is not None and pin.release != int(release):
                continue
            if pin.relpath not in self.certified:
                continue
            for c in pin.candidates:
                if self._sha256(c) == pin.sha256:
                    return rel(c)
        return None

    def control_source(self, release: Optional[int] = None) -> Optional[str]:
        """Where `stage` will cut the control from: the newest certified
        experiments/ file on disk (any release -- a certified control proves
        the ORACLE, not the probe), else the pinned bundled base of
        ``release`` (plugin/assets/genesis/*.rvt, sha-verified)."""
        return self.newest_certified_on_disk() or self.pinned_certified_on_disk(release)

    # Autodesk's own shipped sample files (samples/*.rvt|rfa) are the reader's
    # reference files -- the source every certified lineage (V0/V15/M/H/L1a)
    # built directly on.  They count as certified BASE sources.  The
    # discipline record recommends the orchestrator list them explicitly.
    @staticmethod
    def is_sample_source(relpath: str) -> bool:
        p = rel(relpath)
        return p.startswith("samples/") and os.path.exists(abspath(p))

    def status(self, relpath: Optional[str]) -> Tuple[str, Optional[dict]]:
        """('certified'|'sample'|'failed'|'unknown', entry-or-None).

        The ledger PATH decides first (certified / sample / failed); only a
        path the ledger has never heard of may then be certified BY BYTES:
        its sha256 equals a certified entry's (the alias rule) -> the entry,
        re-keyed to the certified path and stamped 'aliased_from' /
        'alias_sha256' so every reader sees which file stood in."""
        if not relpath:
            return "unknown", None
        p = rel(relpath)
        if p in self.certified:
            return "certified", self.certified[p]
        if self.is_sample_source(p):
            return "sample", {"file": p, "proves": "Autodesk-authored sample (the reader's own "
                                                   "reference file; source of every certified lineage)"}
        if p in self.failed:
            return "failed", self.failed[p]
        hit = self.alias(p)
        if hit:
            cert, digest = hit
            return "certified", {**self.certified[cert], "file": cert,
                                 "aliased_from": p, "alias_sha256": digest}
        return "unknown", None

    def newest_certified_on_disk(self, max_bytes: Optional[int] = None) -> Optional[str]:
        """Newest 'certified' entry whose file exists (the ledger array is
        maintained in chronological order, newest LAST)."""
        for p in reversed(list(self.certified.keys())):
            a = abspath(p)
            if os.path.isfile(a):
                if max_bytes is not None and os.path.getsize(a) > max_bytes:
                    continue
                return p
        return None


