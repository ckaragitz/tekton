_NAME_INDEX: Optional[Dict[str, List[str]]] = None


def _name_index() -> Dict[str, List[str]]:
    """basename -> repo paths, over experiments/ (EXCLUDING the acceptance
    staging copies, which are uploads not sources) and samples/."""
    global _NAME_INDEX
    if _NAME_INDEX is not None:
        return _NAME_INDEX
    idx: Dict[str, List[str]] = {}
    for pat in ("experiments/**/*.rvt", "experiments/**/*.rfa", "samples/*.rvt", "samples/*.rfa"):
        for p in glob.glob(os.path.join(ROOT, pat), recursive=True):
            rp = rel(p)
            if rp.startswith("experiments/acceptance/"):
                continue
            idx.setdefault(os.path.basename(rp), []).append(rp)
    _NAME_INDEX = idx
    return idx


def _resolve_bare_name(name: str) -> Optional[str]:
    """Resolve a bare 'K1.rvt' to its unique repo path (WEAK -- manifests
    should declare full repo paths; ambiguity resolves to None)."""
    hits = _name_index().get(name) or []
    return hits[0] if len(hits) == 1 else None


def _first_path(text: Any) -> Optional[str]:
    """Extract the first .rvt/.rfa/.rte repo path from a free-text field.
    Full repo paths (experiments/..., samples/...) first; failing that a
    UNIQUE bare basename (the legacy subst_v2 form) -- ambiguous bare names
    resolve to nothing, on purpose."""
    if text is None:
        return None
    if isinstance(text, dict):
        for v in text.values():
            got = _first_path(v)
            if got:
                return got
        return None
    if isinstance(text, (list, tuple)):
        for v in text:
            got = _first_path(v)
            if got:
                return got
        return None
    if not isinstance(text, str):
        return None
    m = _PATH_RE.search(text)
    if m:
        return m.group(1)
    am = _ABS_RE.search(text)                                   # absolute paths (some real
    if am:                                                     # manifests, and test corpora)
        return am.group(1)
    for bm in _BARE_RE.finditer(text):
        got = _resolve_bare_name(bm.group(1))
        if got:
            return got
    return None


def _iter_probe_entries(manifest: dict) -> List[Tuple[str, dict]]:
    """[(entry_key, entry)] for a probes.json 'probes' block (list or dict),
    plus the latest-probes convention: a manifest.json 'viewer_queue' list.
    Both are yielded when both exist (a stream may keep build details under
    'probes' and the base declaration under 'viewer_queue')."""
    out: List[Tuple[str, dict]] = []
    for block in ("probes", "viewer_queue"):
        pr = manifest.get(block)
        if isinstance(pr, dict):
            for k, e in pr.items():
                if isinstance(e, dict):
                    out.append((str(k), e))
        elif isinstance(pr, list):
            for i, e in enumerate(pr):
                if isinstance(e, dict):
                    key = str(e.get("name") or e.get("rung") or e.get("id") or e.get("probe") or i)
                    out.append((key, e))
    return out


def is_frontdoor_manifest(manifest: dict) -> bool:
    """True for the front door's own manifest.json (rvt.frontdoor.manifest):
    it carries no 'probes' block but declares the run's base ('base') and
    outputs ('build.files' on the create routes, 'output' on the edit route)."""
    return ("frontdoor" in str(manifest.get("tool") or "")
            and isinstance(manifest.get("base"), dict))


def frontdoor_entries(manifest: dict, pins: Sequence[PinnedBase] = ()) -> List[Tuple[str, dict]]:
    """One probe entry per .rvt/.rfa a front-door manifest.json says it wrote
    ('build.files' / 'output'), each declaring the run's base as an exact path
    under 'base' -- the same field a probes.json uses, so resolution and the
    best-match ordering are shared:

      * manifest.base.sha256 equals a genesis pin's sha256 -> that pin's
        certified relpath (experiments/genesis/.../G_ABPD*.rvt) -- the base
        block of a --target-version 2025 run still embeds the DEFAULT pin, so
        the digest is matched against every release slot, not base.pin only;
      * else base.pin when base.sha256 == base.pin.sha256;
      * else the base file itself (an explicit --base / $RVT_GENESIS_BASE /
        the --rvt route's input): the ledger then judges that path -- by
        path or by bytes -- like any other declared base.
    'release' is the matched pin's, else target_version.output_release;
    'digest_matched' records that the declaration came from sha256 equality.
    Nothing here certifies anything; it only turns the front door's recorded
    lineage into the declaration the gate demands."""
    if not is_frontdoor_manifest(manifest):
        return []
    base = manifest.get("base") or {}
    digest = str(base.get("sha256") or "").lower()
    tv = manifest.get("target_version") if isinstance(manifest.get("target_version"), dict) else {}
    release: Optional[int] = int(tv["output_release"]) if str(tv.get("output_release") or "").isdigit() else None
    pin = next((p for p in pins if digest and digest == p.sha256), None)
    own = base.get("pin") if isinstance(base.get("pin"), dict) else {}
    if pin:
        declared, release = pin.relpath, pin.release
        how = f"base.sha256 {digest[:12]}... == the Revit {pin.release} genesis pin"
    elif digest and own.get("relpath") and digest == str(own.get("sha256") or "").lower():
        declared, how = rel(str(own["relpath"])), f"base.sha256 {digest[:12]}... == base.pin"
    elif base.get("path") or base.get("input_file"):
        declared = rel(str(base.get("path") or base.get("input_file")))
        how = f"base file {declared} (source {base.get('source') or 'input'}; not a genesis pin)"
    else:
        return []
    files = [f for f in list(((manifest.get("build") or {}).get("files") or {}).values())
             + [manifest.get("output")] if isinstance(f, dict)]
    out: List[Tuple[str, dict]] = []
    for f in files:
        p = str(f.get("path") or f.get("relpath") or "")
        if os.path.splitext(p)[1].lower() not in (".rvt", ".rfa", ".rte"):
            continue
        out.append((os.path.splitext(os.path.basename(p))[0],
                    {"file": p, "base": declared, "release": release,
                     "digest_matched": how.startswith("base.sha256"),
                     "declared_by": f"front-door manifest: {how}"}))
    return out


def candidate_manifests(probe_path: str) -> List[str]:
    """Where to look for the probe's declaration: its own directory first
    (probes.json, then manifest.json), then every manifest under
    experiments/."""
    found: List[str] = []
    d = os.path.dirname(abspath(probe_path))
    for name in ("probes.json", "manifest.json"):
        own = os.path.join(d, name)
        if os.path.exists(own):
            found.append(own)
    for pat in ("experiments/**/probes.json", "experiments/**/probes_*.json",
                "experiments/**/manifest.json"):
        for m in sorted(glob.glob(os.path.join(ROOT, pat), recursive=True)):
            if m not in found:
                found.append(m)
    return found


def find_entries(probe_path: str, manifest_override: Optional[str] = None,
                 pins: Optional[Sequence[PinnedBase]] = None
                 ) -> List[Tuple[str, dict, str, dict]]:
    """Every (manifest_path, manifest_dict, entry_key, entry) describing
    ``probe_path``, best matches first: exact repo-path match in the probe's
    own directory manifests, then exact matches elsewhere, then (WEAK) a
    basename-only match -- so a probe staged into experiments/acceptance/ still
    finds its source stream's declaration.  ``pins`` (default: the shipped
    genesis pins) let a front-door manifest.json name its pinned base.
    """
    target = rel(probe_path)
    base_name = os.path.basename(target)
    pins = genesis_pins() if pins is None else pins
    manifests = [abspath(manifest_override)] if manifest_override else candidate_manifests(probe_path)
    exact: List[Tuple[str, dict, str, dict]] = []
    weak: List[Tuple[str, dict, str, dict]] = []
    for mp in manifests:
        try:
            with open(mp) as fh:
                man = json.load(fh)
        except (OSError, ValueError):
            continue
        if not isinstance(man, dict):
            continue
        for key, e in _iter_probe_entries(man) + frontdoor_entries(man, pins):
            f = e.get("file")
            if not f:
                if key == os.path.splitext(base_name)[0]:      # symbol-named entry, no file
                    weak.append((mp, man, key, e))
                continue
            if rel(str(f)) == target:
                exact.append((mp, man, key, e))
            elif os.path.basename(str(f)) == base_name:
                weak.append((mp, man, key, e))
    return exact + weak


class BaseResolution:
    """The declared base of one probe, and where the declaration came from."""

    def __init__(self, probe: str, base: Optional[str], source: str,
                 manifest: Optional[str], raw: Optional[str] = None, *,
                 release: Optional[int] = None, digest_matched: bool = False):
        self.probe = rel(probe)
        self.base = rel(base) if base else None
        self.source = source            # human-readable: which manifest/field
        self.manifest = rel(manifest) if manifest else None
        self.raw = raw                  # the raw declaration text
        self.release = release          # the Revit release the declaring manifest names, if any
        self.digest_matched = digest_matched   # declared by sha256 == a genesis pin, not by prose

    def to_json(self) -> dict:
        return {"probe": self.probe, "base": self.base, "declared_in": self.manifest,
                "declared_by": self.source, "declaration": self.raw,
                "release": self.release, "digest_matched": self.digest_matched}


def resolve_base(probe_path: str, manifest_override: Optional[str] = None,
                 pins: Optional[Sequence[PinnedBase]] = None) -> BaseResolution:
    """Resolve the probe's DECLARED base file from its probes.json entry (or
    the front-door manifest.json that describes it).

    Resolution order (first hit wins), per describing entry (best match
    first, see find_entries):
      1. entry keys in BASE_KEYS order.  A value that names an EXISTING file
         (repo-relative or absolute) is that file, verbatim; a symbolic value
         found in the manifest's top-level 'bases' map -> that base's path;
         'template' -> manifest 'reference_files'[template]; 'parent_rung' ->
         the sibling entry whose rung/name matches (its 'file'); other keys ->
         the first repo path (experiments/... or samples/...) inside the
         value, else a UNIQUE bare filename.
      2. manifest-level MANIFEST_BASE_KEYS (a stream-wide base).
    A probe with no resolvable declaration returns base=None -- the gate
    treats that as a violation (undeclared lineage is not lineage).
    """
    hits = find_entries(probe_path, manifest_override, pins)
    if not hits:
        return BaseResolution(probe_path, None,
                              "no probes.json / front-door manifest.json entry describes this file",
                              None, None)
    last_reason: Optional[BaseResolution] = None
    for mp, man, key, entry in hits:
        got = _resolve_entry(probe_path, mp, man, key, entry)
        if got.base:
            return got
        last_reason = got
    assert last_reason is not None
    return last_reason


def _resolve_entry(probe_path: str, mp: str, man: dict, key: str, entry: dict) -> BaseResolution:
    """Resolve the base from ONE describing entry (see resolve_base)."""
    entries = _iter_probe_entries(man)
    ref_files = man.get("reference_files") if isinstance(man.get("reference_files"), dict) else {}
    bases_map = man.get("bases") if isinstance(man.get("bases"), dict) else {}
    via = f" ({entry['declared_by']})" if entry.get("declared_by") else ""
    meta = {"release": entry.get("release") if isinstance(entry.get("release"), int) else None,
            "digest_matched": bool(entry.get("digest_matched"))}
    for k in BASE_KEYS:
        if k not in entry or entry.get(k) in (None, "", [], {}):
            continue
        val = entry[k]
        raw = json.dumps(val) if not isinstance(val, str) else val
        if isinstance(val, str) and os.path.isfile(abspath(val)):      # an exact, existing path:
            return BaseResolution(probe_path, val,                        # no free-text parsing
                                  f"{rel(mp)} entry {key!r} field {k!r}{via}", mp, raw, **meta)
        # symbolic base (latest-probes convention: "base": "rst" resolved via
        # the manifest's top-level "bases": {"rst": {"path": ...}})
        if isinstance(val, str) and val in bases_map and not _first_path(val):
            got = _first_path(bases_map[val])
            if got:
                return BaseResolution(probe_path, got,
                                      f"{rel(mp)} entry {key!r} field {k!r}={val!r} "
                                      f"(-> manifest 'bases')", mp, raw)
            continue
        if k == "template" and isinstance(val, str):
            # symbolic name resolved through reference_files, else another entry
            ref = ref_files.get(val)
            got = _first_path(ref) if ref is not None else None
            if not got:
                for ek, ee in entries:
                    if ek == val or str(ee.get("rung")) == val or str(ee.get("name")) == val:
                        got = _first_path(ee.get("file"))
                        break
            if got:
                return BaseResolution(probe_path, got,
                                      f"{rel(mp)} entry {key!r} field 'template'={val!r}", mp, raw)
            continue
        if k == "parent_rung" and isinstance(val, str):
            sym = val.split()[0]
            got = None
            for ek, ee in entries:
                if str(ee.get("rung")) == sym or str(ee.get("name")) == sym or ek == sym:
                    got = _first_path(ee.get("file"))
                    break
            if not got:
                got = _first_path(val)          # e.g. "R9 (viewer PASS)" -> anchors map
                if not got:
                    anchors = man.get("known_passing_anchors") or {}
                    if isinstance(anchors, dict) and sym in anchors:
                        got = _first_path(anchors[sym])
            if got:
                return BaseResolution(probe_path, got,
                                      f"{rel(mp)} entry {key!r} field 'parent_rung'={val!r}", mp, raw)
            continue
        got = _first_path(val)
        if got:
            return BaseResolution(probe_path, got,
                                  f"{rel(mp)} entry {key!r} field {k!r}{via}", mp, raw, **meta)
    for k in MANIFEST_BASE_KEYS:
        if k not in man or man.get(k) in (None, "", [], {}):
            continue
        got = _first_path(man[k])
        if got:
            raw = json.dumps(man[k]) if not isinstance(man[k], str) else man[k]
            return BaseResolution(probe_path, got,
                                  f"{rel(mp)} manifest-level field {k!r} (stream-wide base)",
                                  mp, raw)
    return BaseResolution(probe_path, None,
                          f"{rel(mp)} entry {key!r} declares no base "
                          f"(none of {list(BASE_KEYS)} nor manifest-level "
                          f"{list(MANIFEST_BASE_KEYS)} carries a file path)", mp, None)


