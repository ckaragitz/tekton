def _inventory_from_rfa(path: str) -> FamilyInventory:
    from ..families import FamilyIndex
    from ..objects import iter_records
    from ..families import unit_segments
    idx = FamilyIndex(path)
    segs = unit_segments(idx, 0)
    ids = sorted({int(r.elem_id) for r in iter_records(segs[102], 102) if r.elem_id >= 0})
    by_class: Dict[str, List[int]] = collections.defaultdict(list)
    obj_of: Dict[int, dict] = {}
    recs = idx.unit_records(0)[102]
    for eid in ids:
        rec = recs.get(eid)
        cname = idx.class_name(rec.class_id) if rec else "?"
        by_class[cname].append(eid)
        try:
            obj_of[eid] = dict(idx.value(0, eid) or {})
        except Exception:                                # pragma: no cover
            obj_of[eid] = {}
    for v in by_class.values():
        v.sort()
    fam = (by_class.get("Family") or [INVALID])[0]
    return _assemble_inventory(dict(by_class), obj_of, self_family_id=int(fam),
                               document_guid="", name=os.path.basename(path),
                               type_params={})


def _assemble_inventory(by_class: Dict[str, List[int]], obj_of: Dict[int, dict], *,
                        self_family_id: int, document_guid: str, name: str,
                        type_params: Dict[int, str]) -> FamilyInventory:
    ids = {i for v in by_class.values() for i in v}
    levels = list(by_class.get("Level", []))
    refplanes = list(by_class.get("RefPlane", []))
    all_views: List[int] = []
    for c in _VIEW_CLASSES:
        all_views.extend(by_class.get(c, []))
    all_views = sorted(all_views)
    project_view = (by_class.get("DBViewProject") or [INVALID])[0]
    plan_views = sorted(by_class.get("DBViewPlan", []) + by_class.get("DBViewRCPlan", []))
    # level -> the plan views generated from it (m_genElemId), plans in id order
    lpv: Dict[int, List[int]] = {lv: [] for lv in sorted(levels)}
    for pv in plan_views:
        gen = (obj_of.get(pv) or {}).get("m_genElemId")
        if isinstance(gen, int) and gen in lpv:
            lpv[gen].append(pv)
    # sketch planes with an OWNER VIEW that exists (the CurSPRec grammar names
    # the owning DBView; geometry sketch planes are owned by the Family, not a
    # view, and get no CurSPRec -- matching the archetype's 2-of-14 planes)
    view_set = set(all_views)
    sketch_planes: List[Tuple[int, int]] = []
    for sp in by_class.get("SketchPlane", []):
        owner = (obj_of.get(sp) or {}).get("m_ownerDBViewId")
        if isinstance(owner, int) and owner in view_set:
            sketch_planes.append((int(sp), int(owner)))
    # plan view types (for the new-level default-view-type registry)
    pvt: List[int] = []
    for vt in by_class.get("DBViewType", []):
        fam = type_params.get(vt, "")
        if not fam or fam in _PLAN_VIEW_FAMILIES:
            pvt.append(int(vt))
    return FamilyInventory(
        ids=ids, by_class=by_class, obj_of=obj_of,
        self_family_id=int(self_family_id), document_guid=document_guid, name=name,
        project_view=int(project_view), plan_views=plan_views, all_views=all_views,
        drawings=sorted(by_class.get("DBDrawing", [])),
        levels=sorted(levels), refplanes=sorted(refplanes),
        suns=sorted(by_class.get("SunAndShadowSettings", [])),
        units_elem=(by_class.get("UnitsElem") or [INVALID])[0],
        sketch_planes=sketch_planes, level_plan_views=lpv, plan_view_types=pvt)


