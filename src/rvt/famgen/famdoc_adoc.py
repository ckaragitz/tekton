# PART 1 -- THE PARTITION UNIT FOOTER + STREAM END RECORD (counsel C5)
# ===========================================================================
#
# Grammar (a single-unit family partition stream, after the last block):
#
#   unit terminator   u16 0x0f28 + 16 zero bytes                    FORMAT
#   footer blob       u16 0x0f3f + u32 n + n opaque bytes (n=64|0)  n: FORMAT
#                                                                  bytes: PER-UNIT NONCE
#   footer string     u32 char_count(34) + UTF-16LE
#                     "Data generated by Autodesk® Revit®"           FORMAT SIGNATURE
#   end record        u16 0x3a3 + i32 0 + i32 -1  (10 bytes)         FORMAT CONSTANT
#   [ + the final block's CRCIO pad-count/parity = the on-disk framing, NOT
#     stream content; ``container.depage`` leaves it as trailing junk ]
#
# Evidence: :func:`footer_forensics` (2,072 units / 7 files: the six project
#  samples + the family archetype).  The corpus
# note in ``rvt.partitions`` ("end record ... zero padding (0-484 bytes),
# opaque high-entropy tail (48-276 bytes) [undecoded]") is hereby DECODED:
# the tail is the final block's parity (byte-exact ``ecc.unframe_stream``
# round trip on every file); the true end record is the 10-byte constant.

#: the universal unit-terminator SIGNATURE string.  Byte-identical in every
#: unit of every file inspected (2,072/2,073 -- the exception is the tiny
#: ``dach`` Partitions/85 whose text field is EMPTY, n = 0).  We write these
#: bytes ourselves from this constant (they were never copied): a required
#: format token, the analogue of a file magic -- counsel item C5.
DATA_GENERATED_STRING = "Data generated by Autodesk® Revit®"
#: its exact wire bytes = u32 34 (character count) + UTF-16LE (68 B) = 72 B
FOOTER_STRING_BYTES = (struct.pack("<I", len(DATA_GENERATED_STRING))
                       + DATA_GENERATED_STRING.encode("utf-16-le"))

#: the DECODED universal stream end record: u16 0x3a3, i32 0, i32 -1.
#: Identical in 8/8 exactly-unframed partition streams (six projects, one
#: with two streams, + the family archetype -- the degenerate empty-footer
#: ``dach`` unit included).  The extra 48-276 bytes real files show after
#: depaging are the FINAL BLOCK's CRCIO pad-count + parity (framing, not
#: content).
FAMILY_END_RECORD = struct.pack("<Hii", 0x3A3, 0, -1)
assert FAMILY_END_RECORD == bytes.fromhex("a30300000000ffffffff")

