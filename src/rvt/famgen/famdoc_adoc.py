def emit_family_rfa_v2(doc, path: str, *, mode: str = "candidate",
                       footer_mode: str = "nonce",
                       donor: str = TEMPLATE_DONOR,
                       product_name: str = PRODUCT_NAME,
                       username: str = PRODUCT_NAME,
                       timestamp: Optional[int] = TIMESTAMP,
                       write_reports: bool = True) -> Dict[str, Any]:
    """Write ``doc`` (OUR ``FamilyDoc``) as a standalone ``.rfa`` whose EVERY
    stream is ours except the certified per-release schema constant.

    Versus ``skeleton.emit_family_rfa``:

    * ``Global/Latest``  = :func:`author_family_adocument` (OUR document
                            object) framed by the proven Latest stream
                            encoder -- NOT the donor's ADocument;
    * partition stream   = the same block assembler, but the unit footer
                            blob is :func:`build_footer` (ours) and the end
                            record is the DECODED 10-byte constant
                            (:data:`FAMILY_END_RECORD`) -- NO donor footer,
                            NO donor final-block parity junk;
    * Global stream prefixes and the ``Contents`` prologue come from the
      format-constant tables / OUR encoder (not read off the donor);
    * ``BasicFileInfo`` / ``DocumentIncrementTable`` are passed through
      ``rvt.identity`` (our authoring string, no user path, no employee
      username; the cross-stream GUID invariants preserved);
    * ``Formats/Latest`` = the ONE carried stream, sha256-checked as the
      Revit-2026 corpus schema constant.

    Returns the emission report (streams, sizes, what is ours, the read-back
    verification); a ``<stem>_adoc.json`` / ``<stem>_emit.json`` are written
    beside the file when ``write_reports``.
    """
    from .. import ecc
    from .. import identity as _ID
    from .. import stream_encoders as se
    from .. import adocument as A
    from ..cfb_writer import CfbEntry, write_cfb
    from ..container import open_rvt
    from ..writer import gzip_member
    from . import skeleton as SK

    t0 = time.time()
    if not os.path.isfile(donor):
        raise FileNotFoundError(
            "family container source not found: pass donor=<the bundled "
            "genesis base> (rvt.frontdoor.standalone.bundled_base_path()) or "
            f"a user-supplied .rfa. (looked for: {donor})")
    if not doc.finalized:
        doc.finalize()
    ts = int(timestamp if timestamp is not None else time.time())
    # -- OUR document object -----------------------------------------------------
    donor_is_family = container_is_family(donor)
    if donor_is_family:
        ad = author_family_adocument(doc, mode=mode, donor=donor)
        ad["report"]["archetype"] = f"family container archetype: {donor}"
    else:
        # the donor is a PROJECT container (the bundled standalone surface's
        # only container): templating the ADocument from it ships a
        # project-shaped registry set that desktop Revit's family editor
        # terminates on (EditModeMgr.cpp:333 assertion -- issue #52).
        # Author from the schema-constructed famdoc tree instead (the
        # L1a-certified embedded lineage, host form).
        ad = author_family_adocument(
            doc, mode=mode, source_tree=constructive_family_host_tree(doc))
        ad["report"]["archetype"] = (
            "CONSTRUCTIVE famdoc tree (schema-built; donor container is a "
            "project, unusable as a family-document archetype -- issue #52)")
    latest_payload = ad["payload"]
    latest_logical = A.latest_logical_stream(latest_payload, level=3)
    # -- OUR partition save unit + footer + end record ---------------------------
    segs = doc.partition_payloads()
    gm = doc.globals_models(username=username, out_path=path, timestamp=ts)
    dit_model = gm["DocumentIncrementTable"]
    part_name = SK._partition_stream_name(dit_model)
    et_count = len(gm["ElemTable"]["records"])
    guid = str(gm["_ids"]["document_guid"])
    unit_digest_material = b"".join(segs.get(s, b"") for s in (101, 102, 103))
    footer_blob = build_footer(guid=guid, payload=unit_digest_material, mode=footer_mode)
    logical_part = SK.build_partition_stream(segs, elem_table_count=et_count,
                                             footer_blob=footer_blob,
                                             end_record=FAMILY_END_RECORD)
    # -- OUR global table streams -------------------------------------------------
    enc = SK.encode_minimal_globals(gm)
    streams: Dict[str, bytes] = {}
    streams[part_name] = ecc.frame_stream(logical_part)
    for n in ("ElemTable", "History", "DocumentIncrementTable", "PartitionTable"):
        payload_n = enc[n]
        if n == "DocumentIncrementTable":
            # the writer OWNS every save-episode username (V32 mechanism, via rvt.identity)
            payload_n = _ID.own_increment_table_payload(payload_n, username=username)
        streams[f"Global/{n}"] = ecc.frame_stream(
            se.global_prefix(n) + gzip_member(payload_n, level=3, sync_flush=True))
    streams["Global/ContentDocuments"] = ecc.frame_stream(
        se.global_prefix("ContentDocuments")
        + gzip_member(enc["ContentDocuments"], level=3, sync_flush=True))
    streams["Global/Latest"] = ecc.frame_stream(latest_logical)
    # Contents: OUR prologue (encoder) + OUR payload
    pro = se.encode_contents_prologue(gm["ContentsPrologue"])
    streams["Contents"] = ecc.frame_stream(
        pro + gzip_member(enc["Contents"], level=3, sync_flush=True))
    # -- identity: BasicFileInfo through rvt.identity ------------------------------
    ep_guid = str(gm["_ids"]["episode_guid"])
    bfi_model = _ID.own_identity_model(dict(gm["BasicFileInfo"]), out_path=path,
                                       username=username, document_guid=ep_guid,
                                       author=_ID.DEFAULT_AUTHOR,
                                       client_app_name=_ID.DEFAULT_CLIENT_APP)
    streams["BasicFileInfo"] = se.encode_basic_file_info(bfi_model, regenerate_mirror=True)
    streams["TransmissionData"] = SK.our_transmission_data()
    streams["PartAtom"] = doc.part_atom(product_name=product_name)
    # -- the ONE carried stream: the per-release schema constant ------------------
    with open_rvt(donor) as f:
        formats_raw = f.raw("Formats/Latest")
        try:
            formats_inflated = f.inflate("Formats/Latest", 0)
        except Exception:                                   # pragma: no cover
            formats_inflated = b""
    fmt_sha = hashlib.sha256(formats_inflated).hexdigest() if formats_inflated else ""
    fmt_is_constant = bool(FORMATS_LATEST_SHA256_PREFIX
                           and fmt_sha.startswith(FORMATS_LATEST_SHA256_PREFIX))
    streams["Formats/Latest"] = formats_raw
    # -- the container -----------------------------------------------------------
    entries = [CfbEntry(path="", entry_type="root")]
    for storage in ("Formats", "Global", "Partitions"):
        entries.append(CfbEntry(path=storage, entry_type="storage"))
    order = ["BasicFileInfo", "Contents", "Formats/Latest",
             "Global/ContentDocuments", "Global/DocumentIncrementTable",
             "Global/ElemTable", "Global/History", "Global/Latest",
             "Global/PartitionTable", "PartAtom", part_name, "TransmissionData"]
    for name in order:
        entries.append(CfbEntry(path=name, entry_type="stream", data=streams[name]))
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    write_cfb(path, entries)
    rep: Dict[str, Any] = {
        "path": path, "size": os.path.getsize(path), "mode": mode,
        "footer_mode": footer_mode, "elements": len(doc.elements),
        "elem_table_count": et_count, "partition_stream": part_name,
        "logical_partition_bytes": len(logical_part),
        "footer_blob_hex": footer_blob.hex(), "footer_blob_len": len(footer_blob),
        "end_record_hex": FAMILY_END_RECORD.hex(),
        "document_guid": guid, "episode_guid": ep_guid,
        "streams": {k: len(v) for k, v in streams.items()},
        "ours": ["Global/Latest (OUR authored family ADocument)",
                 f"{part_name} save unit (every element) + OUR unit footer blob + the "
                 "universal signature string + the decoded 10-byte end record",
                 "Global/ElemTable", "Global/History", "Global/DocumentIncrementTable",
                 "Global/PartitionTable", "Global/ContentDocuments", "Contents "
                 "(prologue + payload)", "BasicFileInfo (rvt.identity)",
                 "TransmissionData", "PartAtom", "CFB container / gzip / CRCIO framing"],
        "carried": [{"stream": "Formats/Latest", "inflated_bytes": len(formats_inflated),
                     "sha256": fmt_sha, "is_corpus_schema_constant": fmt_is_constant,
                     "why": ("the per-release archive class map, byte-identical in every "
                             "Revit-2026 file (.rvt and .rfa) -- FORMAT, not content")}],
        "adocument": ad["report"],
        "identity": {"author": bfi_model.get("author"), "username": bfi_model.get("username"),
                     "client_app_name": bfi_model.get("client_app_name"),
                     "last_save_path": bfi_model.get("last_save_path"),
                     "unique_document_guid": bfi_model.get("unique_document_guid"),
                     "central_episode_guid": bfi_model.get("central_episode_guid"),
                     "via": "rvt.identity.own_identity_model + own_increment_table_payload"},
        "seconds": round(time.time() - t0, 2),
        "notes": list(getattr(doc, "notes", []) or []),
    }
    rep["verify"] = SK.verify_family_rfa(path)
    if write_reports:
        stem = os.path.splitext(path)[0]
        with open(stem + "_emit.json", "w") as fh:
            json.dump({k: v for k, v in rep.items() if k != "adocument"}, fh,
                      indent=1, default=str)
        with open(stem + "_adoc.json", "w") as fh:
            json.dump(ad["report"], fh, indent=1, default=str)
    return rep


