def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(prog="rvt.famgen.famdoc_adoc",
                                 description="FAMILY-GENESIS: the family-level ADocument codec + "
                                             "the retired partition footer / end record")
    ap.add_argument("--out", default=GENESIS2_OUT, help="output directory (v2 set)")
    ap.add_argument("--mode", default="candidate", choices=sorted(FAMILY_AUTHORING_MODES),
                    help="family ADocument authoring mode")
    ap.add_argument("--footer", default="nonce", choices=["nonce", "empty"],
                    help="unit footer blob form")
    ap.add_argument("--no-load", action="store_true", help="skip the L_v2 famload proof")
    ap.add_argument("--no-forensics", action="store_true", help="skip the footer corpus proof")
    ap.add_argument("--forensics-only", action="store_true",
                    help="only run the footer / end-record corpus forensics and print it")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)
    if a.forensics_only:
        fx = footer_forensics()
        print(json.dumps({"units": fx["units"], "conclusions": fx["conclusions"],
                          "string": fx["string"], "blob": fx["blob"],
                          "end_record": {k: v for k, v in fx["end_record"].items()
                                         if k != "streams"}}, indent=1, default=str))
        return 0
    summary = forge_v2(a.out, mode=a.mode, footer_mode=a.footer,
                       with_load=not a.no_load, with_forensics=not a.no_forensics,
                       verbose=not a.quiet)
    ok = all(f.get("provenance", {}).get("ok") and f.get("validate", {}).get("ok")
             for f in summary.get("families", {}).values())
    if summary.get("load") is not None:
        ok = ok and bool((summary["load"] or {}).get("ok"))
    print(f"FAMILY-GENESIS: families {'ALL CLEAN' if ok else 'FINDINGS'}; "
          f"probes -> {os.path.join(a.out, 'probes.json')}")
    return 0 if ok else 1


if __name__ == "__main__":                                   # pragma: no cover
    sys.exit(main())
