def author_family_adocument_embedded(source, *, mode: str = "candidate",
                                     episode: int = 0,
                                     document_guid: Optional[str] = None,
                                     donor: str = TEMPLATE_DONOR) -> Dict[str, Any]:
    """The EMBEDDED variant of :func:`author_family_adocument`: the object a
    ``Global/ContentDocuments`` entry carries -- the SAME populated-registry
    tree but with the ElemTable and DocumentHistory INLINE, an empty
    ``m_storedByRevitBuild`` and NO trailer (the entry grammar), grafting the
    inline table/history built by ``rvt.famgen.factory.author_embedded_
    adocument`` (proven shape) onto our populated tree.

    The factory's own embedded object carries an all-null 239-slot
    AppInfoManager (the L1a-loading shape); this is the POPULATED
    alternative for a loader that wants to test the registries question in
    the embedded position.  Returns ``{"value", "payload", "self_check"}``.
    """
