def _forge_corpus_policy(tree: dict, policy: str, report: dict) -> None:
    """The Autodesk Forge unit / spec / parameter-group JSON corpus inside
    ESSchemaStorage: a per-release PRODUCT constant (verified byte-identical
    -- same 893 unit-schema + 422 parameter-schema pairs -- in the family
    archetype AND all six project samples).  Carried-and-flagged (candidate)
    or emptied (purity), exactly as genesis-2 (counsel C4-class)."""
    es = _appinfo_body(tree, "ESSchemaStorage")
    if not isinstance(es, dict):
        report["forge_corpus"] = {"action": "absent"}
        return
    fs = es.get("m_storedForgeSchemas") or []
    ps = es.get("m_storedParameterSchemas") or []
    nbytes = sum(8 + 2 * len(p.get("first") or "") + 2 * len(p.get("second") or "")
                 for p in list(fs) + list(ps))
    if policy == "empty":
        es["m_storedForgeSchemas"] = []
        es["m_storedParameterSchemas"] = []
        es["m_dirty"] = 0
        report["forge_corpus"] = {
            "action": "EMPTIED", "documents_removed": len(fs) + len(ps), "bytes_removed": nbytes,
            "why": "purity mode: no Autodesk-authored schema documents carried (the "
                   "reader-tolerance probe of the corpus question)"}
    else:
        report["forge_corpus"] = {
            "action": "CARRIED", "documents": len(fs) + len(ps), "bytes": nbytes,
            "why": ("a per-release PRODUCT constant: the SAME 893 unit-schema + 422 "
                    "parameter-schema pairs, byte-identical in the family archetype AND in "
                    "all six project samples (verified by content hash) -- not sample or "
                    "donor EXPRESSION; the Revit install's Forge unit corpus.  Carried and "
                    "FLAGGED, the counsel C4-class residual beside Formats/Latest -- the "
                    "same posture genesis-2's candidate takes; purity mode empties it")}


