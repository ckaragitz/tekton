def _longest_common_run(payload: bytes, donor: str) -> Dict[str, Any]:
    """Longest common byte run between our Global/Latest payload and the
    donor's, and its classification (the Forge product-corpus region is a
    per-release constant carried in candidate mode; anything else would be
    donor expression)."""
    try:
        from ..container import open_rvt
        with open_rvt(donor) as f:
            dp = f.inflate("Global/Latest", 0)
    except Exception:                                          # pragma: no cover
        return {"note": "donor unavailable"}
    # index donor windows at stride 32; probe OUR payload at EVERY offset so
    # a shared region of >= 96 bytes is always found regardless of its
    # relative alignment (a stride-8/stride-8 probe misses regions whose
    # offset difference is not 8-aligned).  Both payloads are ~1.3 MB.
    W = 64
    STRIDE = 32
    idx: Dict[bytes, int] = {}
    for i in range(0, len(dp) - W + 1, STRIDE):
        idx.setdefault(dp[i:i + W], i)
    best_len, best_at, best_donor_at = 0, -1, -1
    n = len(payload)
    p = 0
    while p + W <= n:
        j = idx.get(payload[p:p + W])
        if j is None:
            p += 1
            continue
        # extend
        a, b = p, j
        while a + 1 < n and b + 1 < len(dp) and payload[a + 1] == dp[b + 1]:
            a += 1
            b += 1
        a0, b0 = p, j
        while a0 > 0 and b0 > 0 and payload[a0 - 1] == dp[b0 - 1]:
            a0 -= 1
            b0 -= 1
        run = a - a0 + 1
        if run > best_len:
            best_len, best_at, best_donor_at = run, a0, b0
        p = a + 1
    cls = "none"
    if best_len:
        seg = payload[best_at:best_at + best_len]
        # the Forge corpus is UTF-16 JSON: look for its vocabulary in the run
        txt = seg[:4096].decode("utf-16-le", "replace") + seg[:4096].decode("utf-8", "replace")
        if "autodesk.spec" in txt or "typeid" in txt or "autodesk.unit" in txt or "schema" in txt:
            cls = "Forge unit/spec/parameter JSON corpus (per-release PRODUCT constant, C4-class)"
        elif best_len < 4096:
            cls = "short structural coincidence (AppInfo shell scaffolding)"
        else:
            cls = "UNCLASSIFIED shared run -- inspect"
    return {"longest_common_run_bytes": best_len, "our_offset": best_at,
            "donor_offset": best_donor_at, "classification": cls,
            "note": ("the residual identity is expected to be the Forge product corpus "
                     "(candidate mode carries it; purity mode empties it) and short "
                     "AppInfo shell scaffolding -- never element ids, names or memory")}


_DONOR_FOOTER_CACHE: Dict[str, Tuple[bytes, bytes]] = {}


def _donor_footer_material(donor: str) -> Tuple[bytes, bytes]:
    """(donor 64-byte footer blob, donor final-block parity junk) so a scan can
    prove neither survives in our stream."""
    hit = _DONOR_FOOTER_CACHE.get(donor)
    if hit is not None:
        return hit
    blob, junk = b"", b""
    try:
        from ..container import open_rvt
        from ..partitions import StreamWalker
        from .. import ecc as _ecc
        with open_rvt(donor) as f:
            pn = f.partition_streams()[0]
            dep = f.logical(pn)
            raw = f.raw(pn)
        w = StreamWalker(dep, inflate=False, keep_data=False)
        if w.units:
            blob = bytes(w.units[0].footer_blob)
        exact = _ecc.unframe_stream(raw)
        if dep.startswith(exact):
            junk = bytes(dep[len(exact):])
    except Exception:                                          # pragma: no cover
        pass
    _DONOR_FOOTER_CACHE[donor] = (blob, junk)
    return blob, junk


