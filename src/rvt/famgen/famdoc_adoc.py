    tree = copy.deepcopy(base["value"])
    minimal = _F.author_embedded_adocument(doc, episode=episode, document_guid=document_guid)
    mv = minimal["value"]
    tree["m_elemTable"] = mv["m_elemTable"]                 # INLINE ElemTable of our elements
