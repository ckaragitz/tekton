def derive_family_inventory(source) -> FamilyInventory:
    """Build the :class:`FamilyInventory` of OUR family document.

    ``source`` = a finalized ``rvt.famgen.skeleton.FamilyDoc`` (the
    constructive path -- classes / object values read off our SkelElements)
    or the path of a family ``.rfa`` whose unit 0 is decoded
    (``rvt.families.FamilyIndex``).
    """
    if isinstance(source, str):
        return _inventory_from_rfa(source)
    doc = source
    if not getattr(doc, "finalized", True):
        doc.finalize()
    by_class: Dict[str, List[int]] = collections.defaultdict(list)
    obj_of: Dict[int, dict] = {}
    for e in doc.elements:
        by_class[e.class_name].append(int(e.elem_id))
        obj_of[int(e.elem_id)] = dict(e.obj or {})
    for v in by_class.values():
        v.sort()
    sf = doc.self_family
    inv = _assemble_inventory(dict(by_class), obj_of,
                              self_family_id=int(sf.elem_id) if sf else INVALID,
                              document_guid=str(getattr(doc, "document_guid", "") or ""),
                              name=str(getattr(doc, "name", "family")),
                              type_params=_view_type_families(doc))
    return inv


def _view_type_families(doc) -> Dict[int, str]:
    """DBViewType id -> its view-family key when our constructor recorded it."""
    out: Dict[int, str] = {}
