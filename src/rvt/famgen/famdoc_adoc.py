def forge_v2(out_dir: str = GENESIS2_OUT, *, mode: str = "candidate",
             footer_mode: str = "nonce", with_load: bool = True,
             with_forensics: bool = True, verbose: bool = True) -> Dict[str, Any]:
    """Build the FAMILY-GENESIS v2 deliverable set:

    * the four re-forged families (three factory + S0e) through the fixed
      path (:func:`emit_family_rfa_v2`), each with the certified family-mode
      validation + :func:`provenance_scan_v2`;
    * ``L_v2_panel_loaded.rvt`` = our v2 panel document loaded into the
      working rst sample by ``rvt.famload`` (the L1a pattern with a real
      equipment family), validated;
    * ``footer_forensics.json`` (the counsel-C5 corpus proof) and
      ``probes.json`` (the five viewer probes, ordered by information value)
      + ``family_genesis.json`` (the summary).
    """
    os.makedirs(out_dir, exist_ok=True)
    t0 = time.time()
    summary: Dict[str, Any] = {"stream": "FAMILY-GENESIS (G4b)", "out_dir": out_dir,
                               "mode": mode, "footer_mode": footer_mode,
                               "families": {}, "load": None, "forensics": None}

    def log(msg: str) -> None:
        if verbose:
            print(msg, flush=True)

    # -- 1. the footer / end-record corpus proof -------------------------------
    if with_forensics:
        log("== footer / end-record forensics (corpus)")
        fx = footer_forensics()
        fpath = os.path.join(out_dir, "footer_forensics.json")
        with open(fpath, "w") as fh:
            json.dump(fx, fh, indent=1, default=str)
        summary["forensics"] = {"path": fpath, "conclusions": fx["conclusions"],
                                "units": fx["units"],
                                "string_universal": fx["string"]["universal"],
                                "blob_distinct": fx["blob"].get("distinct"),
                                "end_record_constant_in": fx["end_record"]["true_end_record_constant_in"]}
        log(f"   {json.dumps(fx['conclusions'], indent=None)}")

    # -- 2. the four families ---------------------------------------------------
    for key, fname, builder in _family_builders():
        path = os.path.join(out_dir, fname)
        log(f"== forge {key} -> {os.path.relpath(path, _ROOT)}")
        t1 = time.time()
        doc = builder()
        if not doc.finalized:
            doc.finalize()
        emit = emit_family_rfa_v2(doc, path, mode=mode, footer_mode=footer_mode,
                                  write_reports=False)   # the combined <stem>.json holds all
        val = validate_family_file(path)
        prov = provenance_scan_v2(path, our_ids={int(e.elem_id) for e in doc.elements})
        rec = {
            "path": path, "elements": len(doc.elements), "name": getattr(doc, "name", key),
            "emit": {k: emit.get(k) for k in ("size", "footer_blob_len", "footer_blob_hex",
                                                 "end_record_hex", "logical_partition_bytes",
                                                 "document_guid", "seconds")},
            "verify": {k: emit["verify"].get(k) for k in ("ok", "gzip_crc_failures",
                                                            "ecc_mismatch", "walker_errors",
                                                            "record_counts")},
            "validate": {"family_mode": val["family_mode"]["verdict"],
                         "family_mode_errors": val["family_mode"]["n_errors"],
                         "family_mode_warnings": val["family_mode"]["n_warnings"],
                         "arbiter_raw": val["arbiter_raw"]["verdict"],
                         "arbiter_raw_errors": val["arbiter_raw"]["n_errors"],
                         "arbiter_raw_error_kinds": val["arbiter_raw"]["errors"],
                         "donor_parity": val.get("donor_parity"), "ok": val["ok"]},
            "provenance": {"ok": prov["ok"], "verdict": prov["verdict"],
                           "checks": prov["checks"],
                           "adocument": {k: prov["adocument"][k] for k in (
                               "inflated_bytes", "decodes_clean", "references_to_our_elements",
                               "dangling_id_refs_gt99", "byte_scan_donor_ids",
                               "donor_name_string_hits", "longest_common_run_with_donor_latest",
                               "owner_family_id", "stored_by_revit_build")},
                           "identity": prov["identity"],
                           "partition_footer": prov["partition_footer"],
                           "carried_constants": prov["carried_constants"]},
            "adocument_summary": {
                "conclusion": emit["adocument"].get("conclusion"),
                "purge_totals": emit["adocument"]["purge"]["totals"],
                "registries": emit["adocument"]["registries"],
                "residual": emit["adocument"].get("residual"),
                "forge_corpus": emit["adocument"].get("forge_corpus"),
            },
            "seconds": round(time.time() - t1, 1),
        }
        with open(os.path.splitext(path)[0] + ".json", "w") as fh:
            json.dump({**rec, "provenance_full": prov, "validate_full": val,
                       "emit_full": {k: v for k, v in emit.items() if k != "adocument"}},
                      fh, indent=1, default=str)
        summary["families"][key] = rec
        log(f"   emit {emit['size']:,} B | verify.ok={emit['verify'].get('ok')} | "
            f"validate family_mode={val['family_mode']['verdict']} "
            f"({val['family_mode']['n_errors']} err) / arbiter_raw="
            f"{val['arbiter_raw']['n_errors']} err | provenance ok={prov['ok']} "
            f"| {rec['seconds']}s")

    # -- 3. the attribution ladder of the flagship panel (like G1a/G1_candidate/
    #        G1b): purity (no Forge corpus), minimal (zero registries), and the
    #        candidate ADocument with the EMPTY footer blob form ---------------
    summary["variants"] = {}
    for vkey, vfile, vmode, vfoot in (
            ("panel_purity", "eaton_prl_400A_42sp_480Y_v2_purity.rfa", "purity", footer_mode),
            ("panel_minimal", "eaton_prl_400A_42sp_480Y_v2_minimal.rfa", "minimal", footer_mode),
            ("panel_emptyfooter", "eaton_prl_400A_42sp_480Y_v2_emptyfooter.rfa", mode, "empty")):
        vpath = os.path.join(out_dir, vfile)
        log(f"== variant {vkey} ({vmode}/{vfoot}) -> {os.path.relpath(vpath, _ROOT)}")
        try:
            vdoc = _family_builders()[0][2]()
            if not vdoc.finalized:
                vdoc.finalize()
            vemit = emit_family_rfa_v2(vdoc, vpath, mode=vmode, footer_mode=vfoot,
                                       write_reports=False)
            vval = validate_family_file(vpath, with_donor_parity=False)
            vprov = provenance_scan_v2(vpath, our_ids={int(e.elem_id) for e in vdoc.elements})
            summary["variants"][vkey] = {
                "path": vpath, "mode": vmode, "footer_mode": vfoot, "size": vemit["size"],
                "latest_stream_bytes": vemit["streams"].get("Global/Latest"),
                "validate_family_mode": vval["family_mode"]["verdict"],
                "family_mode_errors": vval["family_mode"]["n_errors"],
                "provenance_ok": vprov["ok"], "provenance_verdict": vprov["verdict"],
                "longest_common_run_with_donor": (
                    vprov["adocument"]["longest_common_run_with_donor_latest"]),
                "forge_corpus": vemit["adocument"].get("forge_corpus"),
                "conclusion": vemit["adocument"].get("conclusion"),
            }
            log(f"   {vemit['size']:,} B | latest={vemit['streams'].get('Global/Latest'):,} B | "
                f"family_mode={vval['family_mode']['verdict']} | provenance ok={vprov['ok']}")
        except Exception as exc:                              # pragma: no cover
            summary["variants"][vkey] = {"path": vpath, "error": f"{type(exc).__name__}: {exc}"}
            log(f"   variant FAILED: {exc}")

    # -- 4. L_v2: our clean equipment family loaded into a working project ------
    if with_load:
        summary["load"] = _load_v2_panel(out_dir, log=log)

    # -- 5. probes.json + the summary --------------------------------------------
    probes = _probes_manifest(summary)
    with open(os.path.join(out_dir, "probes.json"), "w") as fh:
        json.dump(probes, fh, indent=1, default=str)
    summary["probes"] = [p["id"] for p in probes["probes"]]
    summary["seconds"] = round(time.time() - t0, 1)
    with open(os.path.join(out_dir, "family_genesis.json"), "w") as fh:
        json.dump(summary, fh, indent=1, default=str)
    log(f"== done in {summary['seconds']}s -> {out_dir}")
    return summary


def _load_v2_panel(out_dir: str, *, log=print) -> Dict[str, Any]:
    """L_v2: load our v2 panel document into the working rst sample through
    ``rvt.famload.load_family_document`` (the L1a pattern with a real
    equipment family), then validate the written project."""
    from . import factory as F
    from .. import famload as FL
    from . import skeleton as SK
    out_path = os.path.join(out_dir, "L_v2_panel_loaded.rvt")
    log(f"== L_v2 load panel -> {os.path.relpath(out_path, _ROOT)}")
    rec: Dict[str, Any] = {"path": out_path, "host": RST_SAMPLE}
    t0 = time.time()

    def build_panel(start_id: int = 100000):
        return F.make_panelboard(vendor="eaton", line="pow-r-line", mains_a=400,
                                spaces=42, voltage="480Y/277", mcb=True,
                                mounting="surface", start_id=start_id).doc

    try:
        res = FL.load_family_document(RST_SAMPLE, build_panel, out_path,
                                      name="panel_v2",
                                      report_path=os.path.splitext(out_path)[0] + "_load.json")
        rec.update({"loader": "rvt.famload.load_family_document (four-registry, L1a pattern)",
                    "ok": bool(res.ok), "stop_reason": res.stop_reason,
                    "acceptance": list(res.acceptance)[:6],
                    "plans": [p.as_json() for p in res.plans],
                    "verify": (res.proofs.get("verify_written") or {})})
    except Exception as exc:
        rec.update({"loader": "rvt.famload.load_family_document", "ok": False,
                    "error": f"{type(exc).__name__}: {exc}"})
        log(f"   famload raised: {exc}")
    # certified validation of the written project (project mode)
    if os.path.exists(out_path):
        try:
            from .. import validate as _v
            vr = _v.validate_file(out_path)
            errs = [f for f in vr.findings if f.severity == _v.SEV_ERROR]
            warns = [f for f in vr.findings if f.severity == _v.SEV_WARNING]
            rec["validate_project_mode"] = {
                "verdict": "VALID" if not errs else "INVALID", "n_errors": len(errs),
                "errors": [f"{f.layer} {f.where}: {f.message}" for f in errs][:12],
                "n_warnings": len(warns),
                "warnings": [f"{f.layer} {f.where}: {f.message}" for f in warns][:6]}
            log(f"   L_v2 validate: {rec['validate_project_mode']['verdict']} "
                f"({len(errs)} err, {len(warns)} warn)")
        except Exception as e:                              # pragma: no cover
            rec["validate_project_mode"] = {"error": f"{type(e).__name__}: {e}"}
    rec["seconds"] = round(time.time() - t0, 1)
    return rec


