def load_stream(path: str = DEFAULT_STREAM) -> bytes:
    with open(path, "rb") as f:
        return f.read()


def build(path: str = DEFAULT_STREAM) -> dict:
    data = load_stream(path)
    parser = SchemaParser(data)
    clean_end, err = parser.parse()
    recs = parser.records
    by_ord = parser.by_ordinal

    # ordinal verification: every flagged inline reference must equal the
    # ordinal we independently assigned by definition order.
    ordinal_mismatches = [
        {"ordinal": r["ordinal"], "expected": r["expect"], "name": r["name"]}
        for r in recs if r["expect"] is not None and r["expect"] != r["ordinal"]
    ]

    # per-class output
    classes = []
    tag_counter = Counter()
    tag_examples = defaultdict(list)
    field_type_counter = Counter()
    inherit_edges = []
    ref_counter = Counter()
    for r in recs:
        fields_out = []
        for f in r.get("fields", []):
            d = f["desc"]
            ts = type_string(d, by_ord)
            tag_counter[d["tag_hex"]] += 1
            field_type_counter[ts] += 1
            if len(tag_examples[d["tag_hex"]]) < 4:
                tag_examples[d["tag_hex"]].append(f"{r['name']}.{f['name']}")
            fo = {"name": f["name"], "tag_hex": d["tag_hex"], "type_string": ts,
                  "offset": d["off"]}
            for k in ("ref", "count", "ref2", "k", "sep"):
                if k in d:
                    fo[k] = d[k]
            if "ref" in d:
                target = by_ord.get(d["ref"] & 0x7FFF)
                fo["ref_class"] = target["name"] if target else None
                fo["ref_inline_def"] = bool(d["ref"] & 0x8000)
                if target:
                    ref_counter[target["name"]] += 1
            fields_out.append(fo)
        base_ord = r["base_ref"] & 0x7FFF if r["base_ref"] else None
        base_name = by_ord[base_ord]["name"] if base_ord in by_ord else None
        if base_ord is not None:
            inherit_edges.append((r["name"], base_name or f"class#{base_ord}"))
        classes.append({
            "ordinal": r["ordinal"],
            "class_name": r["name"],
            "offset": r["offset"],
            "end": r.get("end"),
            "depth": r["depth"],
            "base_ordinal": base_ord,
            "base_name": base_name,
            "base_inline_def": bool(r["base_ref"] & 0x8000) if r["base_ref"] else False,
            "version": r.get("version"),
            "field_count": len(r.get("fields", [])),
            "fields": fields_out,
            "trailer_guid_count": len(r.get("trailer_guids", [])),
            "trailer_guids": r.get("trailer_guids", []),
        })

    # coverage: top-level (depth-0) records tile [0, clean_end) exactly
    top = [c for c in classes if c["depth"] == 0]
    tiles_ok = True
    covered = 0
    prev_end = 0
    for c in top:
        if c["offset"] != prev_end:
            tiles_ok = False
        covered += (c["end"] - c["offset"])
        prev_end = c["end"]
    coverage = {
        "stream_size": len(data),
        "clean_end": clean_end,
        "clean_fraction": round(clean_end / len(data), 4),
        "top_level_records_tile_clean_region": tiles_ok and prev_end == clean_end,
        "bytes_covered_by_records": covered,
        "degraded_bytes": len(data) - clean_end,
        "degraded_fraction": round((len(data) - clean_end) / len(data), 4),
        "stop_error": err,
    }

    # statistics / codebook
    gt = pair_ground_truth(recs)
    codebook = []
    for tag, cnt in tag_counter.most_common():
        kind = int(tag[0:2], 16)
        mod = int(tag[2:4], 16)
        codebook.append({
            "tag_hex": tag, "kind": KIND_NAMES.get(kind, "?"),
            "modifier": MOD_NAMES.get(mod, "?"), "count": cnt,
            "examples": tag_examples[tag],
        })
    stats = {
        "record_count": len(recs),
        "top_level_count": len(top),
        "inline_count": len(recs) - len(top),
        "field_count_total": sum(len(r.get("fields", [])) for r in recs),
        "ordinal_base": ORDINAL_BASE,
        "ordinal_last": recs[-1]["ordinal"] if recs else None,
        "ordinal_mismatch_count": len(ordinal_mismatches),
        "ordinal_mismatches": ordinal_mismatches[:20],
        "version_histogram": Counter(r.get("version") for r in recs).most_common(20),
        "most_common_field_types": field_type_counter.most_common(30),
        "most_referenced_classes": ref_counter.most_common(30),
        "inheritance_edge_count": len(inherit_edges),
        "root_class_count": sum(1 for c in classes if c["base_ordinal"] is None),
        "trailer_guid_classes": [(c["class_name"], c["trailer_guid_count"])
                                 for c in classes if c["trailer_guid_count"]],
        "pair_ground_truth": {k: dict(v) for k, v in sorted(gt.items())},
        "name_first_letter_top_level": Counter(c["class_name"][0] for c in top).most_common(),
    }

    idents = harvest_identifiers(data, clean_end)
    ident_summary = Counter((f["class"], f["region"]) for f in idents)
    salvage = salvage_degraded_headers(data, clean_end)
    salvage_names = Counter(s["name"] for s in salvage)
    prof = degradation_profile(data)

    # exhaustiveness check inside the faithful region: every u16-prefixed
    # A-CamelCase harvest hit must be a parsed record name.
    parsed_names_at = {c["offset"] + 4: c["class_name"] for c in classes}
    unaccounted = []
    for f in idents:
        if f["region"] != "clean" or f["prefix"] != 2:
            continue
        if f["class"] in ("class_or_camel_name", "type_string") and f["offset"] not in parsed_names_at:
            # could be a name embedded elsewhere; check it's inside some field/type
            unaccounted.append({"offset": f["offset"], "text": f["text"]})

    return {
        "stream": path,
        "sha256": hashlib.sha256(data).hexdigest(),
        "size": len(data),
        "method": "schema-b: structural/statistical (record-boundary alignment + gap statistics + pair<> ground truth)",
        "grammar": __doc__.split("Derived grammar")[1].split("Class ordinals")[0].strip(),
        "coverage": coverage,
        "stats": stats,
        "codebook": codebook,
        "classes": classes,
        "identifier_harvest_summary": [
            {"class": k[0], "region": k[1], "count": v} for k, v in ident_summary.most_common()],
        "clean_region_unaccounted_u16_identifiers": unaccounted[:50],
        "degraded_region": {
            "start": clean_end,
            "profile_window": 8192,
            "wellformed_field_density_per_window": prof,
            "salvaged_header_candidates_count": len(salvage),
            "salvaged_header_duplication_top": salvage_names.most_common(20),
            "salvaged_headers_sample": salvage[:40],
            "note": ("Content beyond clean_end is scrambled at write time by the "
                     "producer's compressor (see doc); records here are not "
                     "faithfully recoverable from this stream."),
        },
    }


def emit(path_out: str = OUT_JSON, path_in: str = DEFAULT_STREAM) -> dict:
    result = build(path_in)
    os.makedirs(os.path.dirname(path_out), exist_ok=True)
    with open(path_out, "w") as f:
        json.dump(result, f, indent=1)
    return result


