ORDINAL_BASE = 12          # first user class = ordinal 12 (verified below)
IDENT_RE = re.compile(rb"[A-Za-z_][A-Za-z0-9_:<>*&,~ ]*$")

# --- primitive-kind codebook (low byte of the descriptor tag) --------------
# Calibrated statistically from std::pair<> synthetic classes (ground truth)
# plus field-name/value statistics; confidence noted per entry.
KIND_NAMES = {
    0x00: "?kind00",
    0x01: "bool",            # ground truth: std::pair< X, bool >.second
    0x02: "?short/enum16",   # m_flags, m_constrFlags, enum m_typeOfChange  [hypothesis]
    0x03: "?long/enum32",    # UserID.m_id, m_nAtomType, m_viewerFlags       [hypothesis]
    0x04: "int",             # ground truth: std::pair< X, int > (unsigned int also maps here)
    0x05: "unsigned long",   # ground truth: std::pair< unsigned long, X >; ATime.m_msb/m_lsb, m_color
    0x06: "float",           # APropertyFloat.m_value                         [strong]
    0x07: "double",          # ground truth: std::pair< X, double >
    0x08: "AString",         # ground truth: std::pair< X, AString > (always mod 0x60)
    0x09: "GUID",            # GUIDvalue.m_guid
    0x0a: "?classref",      # ClassDefinitionRef.m_ref                        [hypothesis]
    0x0b: "Int64",           # Identifier.m_id64, m_hashNative                [strong]
    0x0c: "?kind0c",
    0x0d: "wrapped",         # array/vector wrapper carrying a nested typedesc
    0x0e: "class",           # user class; a u16 class reference follows
}
# modifier (high byte)
MOD_NAMES = {
    0x00: "value",
    0x01: "ptr",             # pointer flavour 1 (polymorphic object)   [hypothesis]
    0x02: "ptr_owned",       # m_elemTable / m_pAppInfoManager        [hypothesis]
    0x03: "ptr_back",        # m_pACD / m_pADoc (back/weak pointer)    [hypothesis]
    0x10: "array",           # fixed-length array, u32 count
    0x11: "ptrarray",        # fixed-length array of pointers, u32 count
    0x40: "?mod40",
    0x50: "container",       # growable container (vector/set/map-of-pairs)
    0x51: "ptrcontainer",    # container of pointers
    0x52: "?mod52",
    0x60: "str",             # only ever seen with kind 0x08 (AString)
    0x61: "?mod61",
    0x62: "?mod62",
}


class ParseError(Exception):
    pass


class Reader:
    __slots__ = ("d", "pos")

    def __init__(self, data: bytes, pos: int = 0):
        self.d = data
        self.pos = pos

    def u8(self) -> int:
        v = self.d[self.pos]
        self.pos += 1
        return v

    def u16(self) -> int:
        v = struct.unpack_from("<H", self.d, self.pos)[0]
        self.pos += 2
        return v

    def u32(self) -> int:
        v = struct.unpack_from("<I", self.d, self.pos)[0]
        self.pos += 4
        return v

    def take(self, k: int) -> bytes:
        v = self.d[self.pos:self.pos + k]
        self.pos += k
        return v


