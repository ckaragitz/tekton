def type_string(desc: dict, by_ordinal: dict) -> str:
    kind = desc["kind"]
    mod = desc["mod"]
    if kind == 0x0e:
        base = "?ptr" if mod in (0x01, 0x02, 0x03, 0x51, 0x11) else "?"
        if "ref" in desc:
            r = by_ordinal.get(desc["ref"] & 0x7FFF)
            base = r["name"] if r else f"class#{desc['ref'] & 0x7FFF}"
        if mod == 0x00:
            return base
        if mod in (0x01, 0x02, 0x03):
            return "T*"                       # untyped pointer (no static class)
        if mod == 0x10:
            return f"{base}[{desc.get('count')}]"
        if mod == 0x11:
            return f"T*[{desc.get('count')}]"
        if mod == 0x50:
            return f"container< {base} >"
        if mod == 0x51:
            return "container< T* >"
        return f"{base} <mod{mod:02x}>"
    if kind == 0x0d:
        inner = type_string(desc["inner"], by_ordinal) if "inner" in desc else "?"
        if mod == 0x10:
            return f"{inner} [x{desc.get('count')}]"
        return f"container< {inner} >"
    name = KIND_NAMES.get(kind, f"kind{kind:02x}")
    if mod == 0x00:
        return name
    if mod == 0x10:
        return f"{name}[{desc.get('count')}]"
    if mod == 0x50:
        return f"container< {name} >"
    if mod == 0x60:
        return name                       # AString always carries mod 0x60
    return f"{name} <mod{mod:02x}>"


def split_template_args(s: str):
    """Split top-level template arguments: 'A, std::pair< B, C >' -> [A, pair]."""
    out, depth, cur = [], 0, []
    for ch in s:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if cur:
        out.append("".join(cur).strip())
    return out


def pair_ground_truth(records):
    """Ground-truth scalar tags from synthetic std::pair< A, B > classes.

    The class name spells the C++ types of fields `first`/`second`, so the
    descriptor tags of those fields calibrate the codebook with no outside
    knowledge.  Returns {cpp_type: Counter(tag_hex)}.
    """
    gt = defaultdict(Counter)
    for r in records:
        n = r["name"]
        if not (n.startswith("std::pair<") and n.endswith(">")):
            continue
        if len(r.get("fields", [])) != 2:
            continue
        args = split_template_args(n[len("std::pair<"):-1].strip())
        if len(args) != 2:
            continue
        for arg, fld in zip(args, r["fields"]):
            gt[arg][fld["desc"]["tag_hex"]] += 1
    return gt


def harvest_identifiers(data: bytes, clean_end: int):
    """Harvest every length-prefixed identifier candidate (task step 1).

    Two prefix widths occur: u16 (class names / synthetic type strings) and
    u32 (field names).  Classify each and report region (clean vs degraded).
    """
    n = len(data)
    charset = set(b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789_:<>*&,~ ")
    found = []
    i = 2
    while i < n:
        # u32-prefixed (field names, always m_/plain identifiers)
        L4 = struct.unpack_from("<I", data, i - 4)[0] if i >= 4 else 0
        L2 = struct.unpack_from("<H", data, i - 2)[0]
        taken = False
        for width, L in ((4, L4), (2, L2)):
            if 3 <= L <= 200 and i + L <= n:
                s = data[i:i + L]
                if s[0:1].isalpha() and all(c in charset for c in s) and \
                        (i + L >= n or data[i + L] not in charset or True):
                    found.append({"offset": i, "prefix": width, "text": s.decode("latin1")})
                    i += L
                    taken = True
                    break
        if not taken:
            i += 1
    for f in found:
        t = f["text"]
        if t.startswith("m_"):
            cls = "field_name"
        elif t.startswith("std::") or t in ("ElementId", "unsigned int", "unsigned long",
                                           "int", "double", "bool", "AString") or "<" in t:
            cls = "type_string"
        elif re.match(r"^[A-Z][A-Za-z0-9_]+$", t) and any(c.islower() for c in t):
            cls = "class_or_camel_name"
        elif re.match(r"^[a-z][A-Za-z0-9_]+$", t):
            cls = "lower_ident"
        else:
            cls = "other"
        f["class"] = cls
        f["region"] = "clean" if f["offset"] < clean_end else "degraded"
    return found


def salvage_degraded_headers(data: bytes, start: int):
    """In the degraded region, resync on plausible class-record headers
    (u16 0000, u16 len, mostly-printable name, sane base/version/fieldcount).
    These are UNTRUSTED; many are LZ-duplicated copies of clean records."""
    out = []
    n = len(data)
    for i in range(start, n - 40):
        if data[i] or data[i + 1]:
            continue
        L = data[i + 2] | (data[i + 3] << 8)
        if not 4 <= L <= 64 or i + 4 + L + 10 > n:
            continue
        name = data[i + 4:i + 4 + L]
        if not name[0:1].isalpha():
            continue
        printable = sum(1 for c in name if 32 <= c < 127)
        if printable < 0.75 * L:
            continue
        j = i + 4 + L
        base = data[j] | (data[j + 1] << 8)
        version = struct.unpack_from("<I", data, j + 2)[0]
        fc = struct.unpack_from("<I", data, j + 6)[0]
        if version < 4000 and fc < 200 and (base == 0 or (base & 0x8000) or base < 6000):
            out.append({"offset": i, "name": name.decode("latin1"), "base_ref": base,
                        "version": version, "field_count": fc})
    return out


def degradation_profile(data: bytes, window: int = 8192):
    """Density of well-formed u32-prefixed m_ field names per window — the
    statistic that locates the faithful/degraded boundary."""
    ident = re.compile(rb"[A-Za-z_][A-Za-z0-9_]*$")
    n = len(data)
    prof = [0] * ((n // window) + 1)
    i = 4
    while i < n:
        L = struct.unpack_from("<I", data, i - 4)[0]
        if 4 <= L <= 60 and i + L <= n and data[i:i + 2] == b"m_" and ident.match(data[i:i + L]):
            prof[i // window] += 1
            i += L
            continue
        i += 1
    return prof


