class SchemaParser:
    def __init__(self, data: bytes):
        self.data = data
        self.records = []          # in definition order (ordinal order)
        self.by_ordinal = {}

    # -- typedesc -----------------------------------------------------------
    def parse_typedesc(self, p: Reader, depth: int) -> dict:
        start = p.pos
        kind = p.u8()
        mod = p.u8()
        x = p.u16()
        desc = {"tag_hex": f"{kind:02x}{mod:02x}", "kind": kind, "mod": mod,
                "x": x, "off": start}
        if x != 0:
            raise ParseError(f"typedesc pad != 0 ({x:#x}) @ {start:#x}")
        if kind == 0x0e:                               # user class
            if mod in (0x00, 0x40, 0x50, 0x52, 0x60, 0x61, 0x62):
                ref = p.u16()
                desc["ref"] = ref
                if ref & 0x8000:
                    self.parse_record(p, depth + 1, expect=ref & 0x7FFF)
            elif mod == 0x10:
                desc["count"] = p.u32()
                ref = p.u16()
                desc["ref"] = ref
                if ref & 0x8000:
                    self.parse_record(p, depth + 1, expect=ref & 0x7FFF)
            elif mod == 0x11:
                desc["count"] = p.u32()
            elif mod in (0x01, 0x02, 0x03, 0x51):
                pass
            else:
                raise ParseError(f"unknown class mod {mod:#x} @ {start:#x}")
        elif kind == 0x0d:                             # wrapped/typed array
            if mod == 0x10:
                desc["count"] = p.u32()
            elif mod != 0x50:
                raise ParseError(f"unknown 0d mod {mod:#x} @ {start:#x}")
            desc["k"] = p.u32()
            desc["sep"] = p.u8()
            desc["inner"] = self.parse_typedesc(p, depth)
            if desc["inner"]["kind"] == 0x0e:
                desc["ref2"] = p.u16()
        else:                                          # scalar kinds
            if mod == 0x10:
                desc["count"] = p.u32()
            elif mod not in (0x00, 0x01, 0x02, 0x03, 0x40, 0x50, 0x51, 0x60):
                raise ParseError(
                    f"unknown scalar tag kind={kind:#x} mod={mod:#x} @ {start:#x}")
        desc["len"] = p.pos - start
        return desc

    # -- record -------------------------------------------------------------
    def parse_record(self, p: Reader, depth: int, expect=None) -> dict:
        start = p.pos
        marker = p.u16()
        if marker != 0:
            raise ParseError(f"expected 0000 record marker @ {start:#x}, got {marker:#06x}")
        name_len = p.u16()
        if not 1 <= name_len <= 300:
            raise ParseError(f"bad class-name length {name_len} @ {p.pos - 2:#x}")
        name = p.take(name_len)
        if not IDENT_RE.match(name):
            raise ParseError(f"bad class name {name[:32]!r} @ {p.pos - name_len:#x}")
        rec = {"offset": start, "name": name.decode("latin1"), "depth": depth,
               "expect": expect, "ordinal": ORDINAL_BASE + len(self.records)}
        # ordinal is assigned by DEFINITION ORDER (name occurrence order);
        # append before descending so nested definitions number after us.
        self.records.append(rec)
        base = p.u16()
        rec["base_ref"] = base
        if base & 0x8000:
            self.parse_record(p, depth + 1, expect=base & 0x7FFF)
        rec["version"] = p.u32()
        fc = p.u32()
        if fc > 5000:
            raise ParseError(f"absurd field count {fc} @ {p.pos - 4:#x}")
        fields = []
        for _ in range(fc):
            flen = p.u32()
            if not 1 <= flen <= 300:
                raise ParseError(f"bad field-name length {flen} @ {p.pos - 4:#x}")
            fname = p.take(flen)
            if not IDENT_RE.match(fname):
                raise ParseError(
                    f"bad field name {fname[:32]!r} @ {p.pos - flen:#x}")
            td = self.parse_typedesc(p, depth)
            fields.append({"name": fname.decode("latin1"), "desc": td})
        rec["fields"] = fields
        nguid = p.u32()
        if nguid > 100000:
            raise ParseError(f"absurd trailer guid count {nguid} @ {p.pos - 4:#x}")
        rec["trailer_guids"] = [format_guid(p.take(16)) for _ in range(nguid)]
        rec["end"] = p.pos
        return rec

    # -- driver ---------------------------------------------------------------
    def parse(self):
        """Parse records until the grammar breaks; return (clean_end, error)."""
        p = Reader(self.data)
        clean_end = 0
        err = None
        n = len(self.data)
        while p.pos < n:
            try:
                self.parse_record(p, 0)
                clean_end = p.pos
            except (ParseError, struct.error, IndexError) as ex:
                err = f"{type(ex).__name__}: {ex}"
                # drop the partial record that failed
                while self.records and "end" not in self.records[-1]:
                    self.records.pop()
                break
        self.by_ordinal = {r["ordinal"]: r for r in self.records}
        self.clean_end = clean_end
        self.error = err
        return clean_end, err


def format_guid(b: bytes) -> str:
    # standard mixed-endian GUID rendering (data1..3 little-endian)
    d1, d2, d3 = struct.unpack("<IHH", b[:8])
    return f"{d1:08x}-{d2:04x}-{d3:04x}-{b[8:10].hex()}-{b[10:16].hex()}"


