def _cross_file_check():
    """Confirm the schema stream is byte-identical in all six samples."""
    shas = {}
    for s in SAMPLES:
        p = os.path.join(ROOT, "extracted", s, "Formats__Latest.gz", "000.bin")
        if os.path.exists(p):
            with open(p, "rb") as f:
                shas[s] = hashlib.sha256(f.read()).hexdigest()[:16]
    print("-- cross-file identity of Formats/Latest (inflated):")
    for s, h in shas.items():
        print(f"  {h}  {s}")
    print(f"  identical: {len(set(shas.values())) == 1}")


