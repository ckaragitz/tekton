"""schema_b — STRUCTURAL/STATISTICAL decode of the Revit `Formats/Latest`
schema stream (method B, independent cross-validation for schema-a).

Method: no external knowledge of the format is assumed.  The grammar below
was derived purely from (1) length-prefixed identifier harvesting, (2)
record-boundary alignment (records tile the byte stream exactly), and (3)
gap statistics between consecutive field names, which reveal the byte
length of every field-descriptor tag.  Scalar type codes are calibrated
statistically: the schema defines synthetic template classes named e.g.
``std::pair< ElementId, int >`` whose ``second`` field descriptor is the
tag for C++ ``int`` — a ground truth generated by the format itself.

Derived grammar (all little-endian; see docs/streams/01-schema-b.md):

    stream      := record*                       (top-level classes, alphabetical)
    record      := u16 marker(=0) u16 nameLen name[nameLen]
                   u16 baseRef                   (0 = none; 0x8000|ord = inline
                                                  definition of the base follows
                                                  as a nested record)
                   [record if baseRef & 0x8000]
                   u32 version u32 fieldCount
                   field[fieldCount]
                   u32 nGuid guid[nGuid]         (16-byte GUIDs; usually 0)
    field       := u32 nameLen name[nameLen] typedesc
    typedesc    := u8 kind u8 mod u16 zero
                   kind==0x0e (class):  mod in {00,50,..}: u16 ref [record if flagged]
                                        mod == 10:        u32 count u16 ref [record]
                                        mod == 11:        u32 count            (ptr array)
                                        mod in {01,02,03,51}: nothing        (pointers)
                   kind==0x0d (typed):  [mod==10: u32 count] u32 k u8 sep typedesc [u16 ref]
                   other kinds:         mod==10: u32 count ; else nothing

Class ordinals: a reference with the high bit set (0x8000|N) means "class N
is defined right here, inline"; classes are numbered in definition order
starting at 12 (ordinals 0..11 are reserved — [hypothesis] built-in kinds).
The parser verifies this: every flagged reference equals 12 + index.

IMPORTANT LIMITATION (see the doc): the inflated stream is byte-faithful
for its first ~0x21e5c bytes (through record ~1150, class names A..DDG,
alphabetical) and is scrambled beyond that point — a decade-old writer-side
defect present identically in every Revit release we could test.  This
module decodes the faithful prefix exhaustively and *characterises* the
degraded remainder rather than pretending to parse it.

Output: ``extracted/_schema/schema_b.json``.
"""
