@dataclass
class RecordHeader:
    offset: int      # offset within the buffer walked
    elem_id: int
    stamp: Optional[int]   # only for seq 102/103 headers
    body_size: int
    cls: int
    hdr_len: int


def record_header_len(seq: int) -> int:
    return RECORD_HDR_101 if seq == 101 else RECORD_HDR_10X


def parse_record_header(buf: bytes, p: int, seq: int) -> RecordHeader:
    if seq == 101:
        eid, size, cls = struct.unpack_from('<qII', buf, p)
        return RecordHeader(p, eid, None, size, cls, RECORD_HDR_101)
    eid, stamp, size, cls = struct.unpack_from('<qIII', buf, p)
    return RecordHeader(p, eid, stamp, size, cls, RECORD_HDR_10X)


def scan_element_headers(buf: bytes, seq: int, limit: Optional[int] = None) -> Iterator[RecordHeader]:
    """Iterate record headers over a segment buffer produced by
    PartitionStream.concat_segment (size-repeats already removed).

    Stops when a header no longer looks plausible (id or size out of range).
    """
    hlen = record_header_len(seq)
    p = 0
    n = len(buf)
    count = 0
    while p + hlen <= n:
        rh = parse_record_header(buf, p, seq)
        if not (-1 <= rh.elem_id < (1 << 40)) or rh.body_size > (1 << 30):
            return
        yield rh
        count += 1
        if limit and count >= limit:
            return
        p += hlen + rh.body_size


