@dataclass
class PartitionStream:
    project: str
    name: str
    raw_size: int
    clean_size: int
    n_pages: int
    header: StreamHeader
    blocks: List[Block]
    units: List[Unit]
    end_offset: int          # clean (de-paged) offset
    end_record: bytes
    errors: List[str]
    page_trailers: List[bytes] = field(default_factory=list)

    def blocks_by_seq(self) -> Dict[int, List[Block]]:
        out: Dict[int, List[Block]] = {}
        for b in self.blocks:
            out.setdefault(b.seq, []).append(b)
        return out

    def concat_segment(self, seq: int) -> bytes:
        """Concatenate inflated payloads of one sub-stream (seq) in stream order.

        Pure concatenation of block payloads reconstructs the segment as a
        contiguous sequence of records [header][body][header][body]... --
        records that span blocks join up seamlessly (verified: the next record
        header follows the spanning body immediately).
        """
        return b''.join(b.data for b in self.blocks if b.seq == seq and b.data)


def partition_stream_paths(project: str) -> List[str]:
    d = os.path.join(EXTRACTED, project)
    return sorted(
        os.path.join(d, fn) for fn in os.listdir(d)
        if fn.startswith('Partitions__') and fn.endswith('.bin')
        # exclude the de-paged .logical.bin artefact written by
        # tools/build_corpus.py, which would otherwise be walked twice
        # (object-decoder found this produced phantom duplicate records)
        and not fn.endswith('.logical.bin')
    )


def load_stream(path: str, inflate: bool = True, keep_data: bool = True) -> PartitionStream:
    """Load a Partitions/<N> stream: de-page, then walk the framing."""
    with open(path, 'rb') as fh:
        raw = fh.read()
    clean, trailers = depage(raw)
    w = StreamWalker(clean, inflate=inflate, keep_data=keep_data)
    project = path.split(os.sep)[-2]
    return PartitionStream(project, os.path.basename(path)[:-4], len(raw), len(clean),
                           len(trailers) + 1, w.header, w.blocks, w.units,
                           w.end_offset, w.end_record, w.errors, trailers)


def concat_elements(project: str = 'racbasicsampleproject', seq: int = 101) -> bytes:
    """Joined element-data buffer for one sub-stream across a project's partitions."""
    parts = []
    for p in partition_stream_paths(project):
        parts.append(load_stream(p).concat_segment(seq))
    return b''.join(parts)


