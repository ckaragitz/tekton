@dataclass
class StreamHeader:
    version: int          # 9
    zero0: int            # 0
    class_ordinal: int    # 0x3a3
    zero1: int            # 0 (i32)
    elem_table_count: int  # == Global/ElemTable count field
    size: int = 18

    def dump(self) -> str:
        return (f'stream header: version={self.version} zero0={self.zero0} '
                f'class=0x{self.class_ordinal:x} zero1={self.zero1} '
                f'elem_table_count={self.elem_table_count}')


def parse_stream_header(raw: bytes) -> StreamHeader:
    version, zero0, cls, zero1, cnt = struct.unpack_from('<IIHiI', raw, 0)
    if version != 9 or cls != CONTAINER_CLASS:
        raise ValueError(f'unexpected Partitions header: v={version} cls=0x{cls:x}')
    return StreamHeader(version, zero0, cls, zero1, cnt)


@dataclass
class Block:
    index: int
    unit: int              # save-unit index (0 = original save)
    hdr_offset: int        # offset of the u16 0x0f28 tag
    flags: int             # 4/5/6/7
    n_records: int         # A
    size_hint: int         # B
    body_bytes: int        # C
    seq: int               # 101/102/103
    z: int                 # 0
    member_offset: int     # offset of the gzip magic
    member_len: int        # physical gzip member bytes (up to trailer tag)
    trailer_ok: bool       # trailer marker found where B says (member+8 == B)
    data: Optional[bytes] = None
    crc_ok: Optional[bool] = None      # gzip (crc32, isize) validates our output
    isize: Optional[int] = None        # ISIZE stored in the gzip trailer

    @property
    def intended_len(self) -> int:
        """Uncompressed length implied by the header (== gzip ISIZE).

        hdr_len(seq)*A + C, with a +/-4 adjustment for the u32 size-repeat
        that closes a block-spanning record: flags 6 (record starts here and
        continues) -> -4, flags 5 (spanning record ends here) -> +4,
        flags 4 / 7 -> 0.  Exact on all 13,535 blocks of the corpus.
        """
        return (record_header_len(self.seq) * self.n_records + self.body_bytes
                + _ISIZE_ADJ.get(self.flags, 0))

    def brief(self) -> str:
        return (f'blk{self.index:5d} u{self.unit:3d} @0x{self.hdr_offset:08x} '
                f'flags={self.flags} A={self.n_records:5d} B={self.size_hint:6d} '
                f'C={self.body_bytes:7d} seq={self.seq} member={self.member_len:6d} '
                f'infl={len(self.data) if self.data is not None else "?"} '
                f'crc_ok={self.crc_ok} intended={self.intended_len}')


@dataclass
class Unit:
    index: int
    first_block: int
    n_blocks: int = 0
    guid: Optional[bytes] = None       # from the separator preceding this unit
    counter: Optional[int] = None      # u32 in the separator
    footer_offset: Optional[int] = None
    footer_blob: bytes = b''
    footer_text: str = ''
    prefix_blob: bytes = b''   # opaque bytes between separator and first block


def _inflate_member(raw: bytes, start: int, end: int) -> Tuple[bytes, bool, int]:
    """Inflate a gzip member occupying raw[start:end] (incl. 10B hdr, 8B trailer).

    Returns (data, crc_ok, stored_isize).  Uses raw inflate; the stored gzip
    trailer validates our output only for ~83 % of members.
    """
    body = raw[start + 10:end - 8]
    stored_crc, stored_isize = struct.unpack_from('<II', raw, end - 8)
    d = zlib.decompressobj(-zlib.MAX_WBITS)
    try:
        out = d.decompress(body) + d.flush()
    except zlib.error:
        return b'', False, stored_isize
    crc_ok = (zlib.crc32(out) & 0xFFFFFFFF) == stored_crc and \
        (len(out) & 0xFFFFFFFF) == stored_isize
    return out, crc_ok, stored_isize


def _find_block_header(raw: bytes, start: int, limit: int = 65536) -> int:
    """Find the next plausible block header (0x0f28 with flags in 4..7)."""
    end = min(len(raw), start + limit)
    q = start
    while True:
        q = raw.find(b'\x28\x0f', q, end)
        if q < 0:
            return -1
        if q + 26 <= len(raw):
            flags = struct.unpack_from('<I', raw, q + 2)[0]
            if flags in (4, 5, 6, 7) and raw[q + 26:q + 29] == b'\x1f\x8b\x08':
                return q
        q += 1


class StreamWalker:
    """Walks the physical framing: header, units, blocks, footers, end record."""

    def __init__(self, raw: bytes, inflate: bool = True, keep_data: bool = True):
        self.raw = raw
        self.inflate = inflate
        self.keep_data = keep_data
        self.header = parse_stream_header(raw)
        self.blocks: List[Block] = []
        self.units: List[Unit] = []
        self.end_offset: int = 0          # offset of the stream end record
        self.end_record: bytes = b''
        self.errors: List[str] = []
        self._walk()

    def _walk(self) -> None:
        raw = self.raw
        n = len(raw)
        pos = self.header.size
        unit = Unit(index=0, first_block=0)
        self.units.append(unit)
        while pos + 2 <= n:
            (tag,) = struct.unpack_from('<H', raw, pos)
            if tag == BLOCK_TAG and raw[pos:pos + 18] == TERMINATOR:
                # unit footer
                pos = self._read_footer(unit, pos)
                if pos < 0:
                    return
                # what follows: unit separator (a3 03 -1 a2 03 ...) or end record
                if raw[pos:pos + 6] == struct.pack('<Hi', CONTAINER_CLASS, -1) \
                        and struct.unpack_from('<H', raw, pos + 6)[0] == UNIT_INNER_CLASS:
                    counter = struct.unpack_from('<I', raw, pos + 8)[0]
                    guid = raw[pos + 12:pos + 28]
                    pos += 28
                    unit = Unit(index=len(self.units), first_block=len(self.blocks),
                                guid=guid, counter=counter)
                    self.units.append(unit)
                    if raw[pos:pos + 2] != struct.pack('<H', BLOCK_TAG):
                        # tolerate unexpected bytes between a separator and
                        # the next block header (never seen after de-paging)
                        nxt = _find_block_header(raw, pos)
                        if nxt < 0:
                            self.end_offset = pos
                            self.end_record = raw[pos:]
                            return
                        unit.prefix_blob = raw[pos:nxt]
                        self.errors.append(f'skipped {nxt-pos} bytes after separator at {pos}')
                        pos = nxt
                    continue
                # end record
                self.end_offset = pos
                self.end_record = raw[pos:]
                return
            if tag != BLOCK_TAG:
                self.errors.append(f'unexpected tag 0x{tag:04x} at {pos}')
                self.end_offset = pos
                self.end_record = raw[pos:]
                return
            _tag, flags, A, B, C, seq, z = struct.unpack_from('<HIIIIII', raw, pos)
            member = pos + 26
            trailer_pat = struct.pack('<HI', TRAILER_TAG, B)
            guess = member + B - 8
            if guess + 6 <= n and raw[guess:guess + 6] == trailer_pat:
                end = guess
                trailer_ok = True
            else:
                end = raw.find(trailer_pat, member)
                trailer_ok = False
                if end < 0:
                    self.errors.append(f'no trailer for block at {pos} (B={B})')
                    self.end_offset = pos
                    self.end_record = raw[pos:]
                    return
            blk = Block(len(self.blocks), unit.index, pos, flags, A, B, C, seq, z,
                        member, end - member, trailer_ok)
            if self.inflate:
                data, ok, isize = _inflate_member(raw, member, end)
                blk.crc_ok, blk.isize = ok, isize
                blk.data = data if self.keep_data else None
                blk._len = len(data)  # type: ignore[attr-defined]
            self.blocks.append(blk)
            unit.n_blocks += 1
            pos = end + 6
        # walked off the end without an end record
        self.end_offset = pos
        self.end_record = raw[pos:]

    def _read_footer(self, unit: Unit, pos: int) -> int:
        raw = self.raw
        unit.footer_offset = pos
        p = pos + 18
        if p + 6 > len(raw) or struct.unpack_from('<H', raw, p)[0] != FOOTER_TAG:
            self.errors.append(f'footer tag missing at {p}')
            self.end_offset = pos
            self.end_record = raw[pos:]
            return -1
        (blen,) = struct.unpack_from('<I', raw, p + 2)
        unit.footer_blob = raw[p + 6:p + 6 + blen]
        p += 6 + blen
        (nchars,) = struct.unpack_from('<I', raw, p)
        p += 4
        unit.footer_text = raw[p:p + 2 * nchars].decode('utf-16-le', 'replace')
        return p + 2 * nchars


def iter_blocks(raw: bytes, inflate: bool = True) -> Iterator[Block]:
    """Yield every framed block of a raw Partitions/<N> stream, in order."""
    yield from StreamWalker(raw, inflate=inflate).blocks


