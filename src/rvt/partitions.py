"""Decoders for `Global/PartitionTable` and `Partitions/<N>` streams.

See docs/streams/05-partitions.md for the derived layouts, worked
examples and confidence levels.  Everything below is verified byte-for-byte
against the six Revit 2026 samples unless marked [hypothesis].

Global/PartitionTable (inflated, 87-179 bytes) -- a *workset* table
    u16   class ordinal 0x0c80 (3200)                   [hypothesis: name]
    u32   version = 1
    u32   entry_count (= 1 in every sample: only the default workset)
    entry_count x
        16B  GUID   (workset unique id; the 4 template-born files share
                     {E3E052F8-0156-11D5-9301-0000863F27AD})
        u32  0
        u32  id_a   (352 / 254 / 131 -- per file)
        u32  id_b   (824 / 596 / 776 / 556 / 989 / 2654 -- per file)
        i32  -1
        u32  kind   (0 user workset, 1 "Project Standards", 2 "Family : ...")
        u8   0
        u32  name_len + UTF-16LE name
        u32 1, u32 1, u32 0, u32 1, u32 0

STREAM PAGING (applies to EVERY OLE stream, not just Partitions):
    the raw stream bytes are stored in 64,896-byte pages, each full page
    followed by a 353-byte page-trailer record (opaque, high entropy, first
    byte always 0x00).  De-page first (`depage()`); everything below is in
    de-paged ("clean") offsets.  raw_off = clean_off + 353 * (clean_off // 64896).

Partitions/<N> (de-paged; NOT gzip at offset 0)
    Stream header (18 bytes)
        u32  9                 -- record/format version (constant)
        u32  0
        u16  0x3a3             -- container class ordinal [hypothesis]
        i32  0
        u32  elem_table_count  == count field of Global/ElemTable
    then 1..n "save units", each a run of framed compressed blocks
        block:
            u16  0x0f28 (3880)  block header tag
            u32  flags          4 = whole records only, 6 = last record
                                continues into the next block, 7 = pure
                                continuation, 5 = starts inside a spanning
                                record that ends here (bit2 always set,
                                bit1 = "record continues", bit0 =
                                "continues previous")
            u32  A  n_records   record headers that START in this block
            u32  B  size_hint   = 8 + gzip member length (bytes from the seq
                                field to the member end); mirrored in the
                                trailer.  100 % after de-paging.
            u32  C  body_bytes  record body bytes stored in this block
                                (ISIZE == hdr_len(seq)*A + C + adj(flags),
                                 hdr_len = 16 for seq 101, 20 for 102/103,
                                 adj = {4: 0, 5: +4, 6: -4, 7: 0})
            u32  seq            101 / 102 / 103 -- logical sub-stream id
            u32  0
            gzip member         1f 8b 08 00 00 00 00 00 00 0b + raw deflate +
                                (crc32, isize); the trailer VALIDATES for
                                every block once the stream is de-paged
            u16  0x0f21 (3873)  trailer tag
            u32  B              copy of the header's B
        unit terminator + footer:
            u16  0x0f28 + u32 0 + u32 0 + u32 0 + u32 0     (18 bytes)
            u16  0x0f3f (3903) + u32 blob_len + blob (0 or 64 opaque bytes)
            u32  n + UTF-16LE string "Data generated by Autodesk(R) Revit(R)"
                 (n = 0 in the tiny dach Partitions/85)
        unit separator (28 bytes, precedes the next unit's first block):
            u16 0x3a3, i32 -1, u16 0x3a2, u32 counter, 16B GUID
            (the GUID also appears in Global/Latest and Global/
             ContentDocuments -> save/episode identity)
    stream end record (after the last footer):
        u16 0x3a3, i32 0, i32 -1, u32 0, zero padding (0-484 bytes),
        opaque high-entropy tail (48-276 bytes)             [undecoded]

Record framing inside the concatenated per-seq byte stream:
    seq 101      16-byte header { i64 id, u32 body_size, u32 cls } + body
                 (cls == 0x5e5 = 1509 for essentially every record)
    seq 102/103  20-byte header { i64 id, u32 stamp, u32 body_size, u32 cls }
                 + body
    A record whose body spans blocks (flags 6/7/5 chain) is closed by a u32
    repeat of body_size after its last body byte.
"""
