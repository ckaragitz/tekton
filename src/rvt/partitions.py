def _fmt_counter(c: Counter, top: int = 8) -> str:
    return ', '.join(f'{k}:{v}' for k, v in c.most_common(top))


def block_length(b: Block) -> Optional[int]:
    if b.data is not None:
        return len(b.data)
    return getattr(b, '_len', None)


def report_stream(path: str, deep: bool = True, sample_records: int = 3) -> None:
    s = load_stream(path, keep_data=deep)
    print(f'\n=== {s.project} / {s.name}  ({s.raw_size:,} raw bytes -> '
          f'{s.clean_size:,} after removing {s.n_pages-1} page trailers)')
    print('  ' + s.header.dump())
    nblk = len(s.blocks)
    crc_ok = sum(1 for b in s.blocks if b.crc_ok)
    seqc = Counter(b.seq for b in s.blocks)
    flagc = Counter(b.flags for b in s.blocks)
    print(f'  units={len(s.units)}  blocks={nblk}  gzip-trailer-valid={crc_ok} '
          f'({100.0*crc_ok/max(nblk,1):.1f}%)  seq={dict(sorted(seqc.items()))}  '
          f'flags={dict(sorted(flagc.items()))}')
    b_len = sum(1 for b in s.blocks if b.trailer_ok)
    lin = sum(1 for b in s.blocks if block_length(b) == b.intended_len)
    isz = sum(1 for b in s.blocks if b.isize == b.intended_len)
    print(f'  B==8+member: {b_len}/{nblk}   ISIZE==hdrlen*A+C+adj: {isz}/{nblk}   '
          f'inflated==intended: {lin}/{nblk}')
    total = sum(block_length(b) or 0 for b in s.blocks)
    print(f'  inflated total = {total:,} bytes; end record @{s.end_offset} '
          f'({len(s.end_record)} bytes); errors={s.errors[:2]}')
    if s.units:
        u0, ul = s.units[0], s.units[-1]
        print(f'  unit0: blocks={u0.n_blocks} footer_blob={len(u0.footer_blob)}B '
              f'text={u0.footer_text[:30]!r}')
        if len(s.units) > 1:
            u1 = s.units[1]
            print(f'  unit1: guid={fmt_guid(u1.guid) if u1.guid else None} '
                  f'counter={u1.counter} blocks={u1.n_blocks}')
            print(f'  last unit {ul.index}: guid={fmt_guid(ul.guid) if ul.guid else None} '
                  f'counter={ul.counter} blocks={ul.n_blocks}')
    for b in s.blocks[:3]:
        print('   ' + b.brief())
    if not deep or not s.blocks:
        return
    for seq in sorted(seqc):
        seg = s.concat_segment(seq)
        cls: Counter = Counter()
        ids = set()
        nrec = 0
        endp = 0
        for rh in scan_element_headers(seg, seq):
            nrec += 1
            cls[rh.cls & 0xFFFF] += 1
            ids.add(rh.elem_id)
            endp = rh.offset + rh.hdr_len + rh.body_size
        walk_ok = endp == len(seg)
        print(f'   seq {seq}: {seqc[seq]} blocks -> segment {len(seg):,} bytes; '
              f'record walk covers {endp:,} ({"COMPLETE" if walk_ok else "PARTIAL"}); '
              f'{nrec:,} records, {len(ids):,} distinct ids; top cls: {_fmt_counter(cls, 6)}')
        shown = 0
        for rh in scan_element_headers(seg, seq, limit=sample_records):
            stamp = f' stamp=0x{rh.stamp:08x}' if rh.stamp is not None else ''
            body = seg[rh.offset + rh.hdr_len:rh.offset + rh.hdr_len + 20]
            print(f'      rec id={rh.elem_id} size={rh.body_size} cls=0x{rh.cls:x}'
                  f'{stamp} body[:20]={body.hex(" ")}')
            shown += 1


def main(argv: List[str]) -> int:
    projects = [a for a in argv if not a.startswith('-')] or SAMPLES
    deep = '--shallow' not in argv
    print('#### Global/PartitionTable ####')
    for proj in SAMPLES:
        try:
            pt = load_partition_table(proj)
        except FileNotFoundError:
            continue
        print(f'--- {proj}')
        print(pt.dump())
    print('\n#### Partitions/<N> ####')
    for proj in projects:
        for path in partition_stream_paths(proj):
            report_stream(path, deep=deep)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
