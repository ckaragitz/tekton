BLOCK_TAG = 0x0F28       # 3880 block header marker
TRAILER_TAG = 0x0F21     # 3873 block trailer marker
FOOTER_TAG = 0x0F3F      # 3903 footer blob marker
CONTAINER_CLASS = 0x3A3  # 931  stream header / unit separator / end record
UNIT_INNER_CLASS = 0x3A2  # 930  inside the unit separator
PT_CLASS = 0x0C80        # 3200 class ordinal leading Global/PartitionTable

RECORD_HDR_101 = 16      # i64 id, u32 size, u32 cls
RECORD_HDR_10X = 20      # i64 id, u32 stamp, u32 size, u32 cls

TERMINATOR = struct.pack('<HIIII', BLOCK_TAG, 0, 0, 0, 0)  # 18 bytes

# stream paging: every OLE stream is written as 64,896-byte pages, each
# full page followed by a 353-byte page trailer that must be excised before
# any gzip member is inflated (verified: 100 % gzip CRC/ISIZE match after)
PAGE_SIZE = 64896        # 0xFD80 payload bytes per page
PAGE_TRAILER = 353       # opaque per-page record (first byte 0x00)
PAGE_STRIDE = PAGE_SIZE + PAGE_TRAILER  # 65249

_ISIZE_ADJ = {4: 0, 5: 4, 6: -4, 7: 0}


def depage(raw: bytes) -> Tuple[bytes, List[bytes]]:
    """Remove the 353-byte page trailers. Returns (clean_bytes, trailers)."""
    if len(raw) <= PAGE_SIZE:
        return raw, []
    out = bytearray()
    trailers: List[bytes] = []
    pos = 0
    n = len(raw)
    while pos < n:
        out += raw[pos:pos + PAGE_SIZE]
        if pos + PAGE_SIZE < n:
            trailers.append(raw[pos + PAGE_SIZE:pos + PAGE_STRIDE])
        pos += PAGE_STRIDE
    return bytes(out), trailers


def clean_to_raw_offset(clean_off: int) -> int:
    """Map an offset in the de-paged stream back to the raw OLE stream."""
    return clean_off + PAGE_TRAILER * (clean_off // PAGE_SIZE)


