@dataclass
class PartitionTableEntry:
    guid: bytes
    zero0: int
    id_a: int
    id_b: int
    minus_one: int
    kind: int
    name: str
    tail: Tuple[int, ...]

    def guid_str(self) -> str:
        return fmt_guid(self.guid)


@dataclass
class PartitionTable:
    class_ordinal: int
    version: int
    count: int
    entries: List[PartitionTableEntry]
    trailing: bytes

    def dump(self) -> str:
        lines = [f'PartitionTable class=0x{self.class_ordinal:04x} version={self.version} count={self.count}']
        for i, e in enumerate(self.entries):
            lines.append(
                f'  [{i}] guid={e.guid_str()} zero0={e.zero0} id_a={e.id_a} id_b={e.id_b} '
                f'minus_one={e.minus_one} kind={e.kind} name={e.name!r} tail={e.tail}')
        if self.trailing:
            lines.append(f'  trailing {len(self.trailing)} bytes: {self.trailing.hex(" ")}')
        return '\n'.join(lines)


def fmt_guid(g: bytes) -> str:
    d1, d2, d3 = struct.unpack('<IHH', g[:8])
    d4 = g[8:16]
    return f'{{{d1:08X}-{d2:04X}-{d3:04X}-{d4[:2].hex().upper()}-{d4[2:].hex().upper()}}}'


def parse_partition_table(buf: bytes) -> PartitionTable:
    """Parse the inflated Global/PartitionTable payload."""
    cls, version, count = struct.unpack_from('<HII', buf, 0)
    if cls != PT_CLASS:
        raise ValueError(f'unexpected PartitionTable class ordinal 0x{cls:x}')
    p = 10
    entries: List[PartitionTableEntry] = []
    for _ in range(count):
        guid = buf[p:p + 16]
        p += 16
        zero0, id_a, id_b, minus_one, kind = struct.unpack_from('<IIIiI', buf, p)
        p += 20
        flag = buf[p]           # u8, 0 in every sample
        p += 1
        (nchars,) = struct.unpack_from('<I', buf, p)
        p += 4
        name = buf[p:p + 2 * nchars].decode('utf-16-le')
        p += 2 * nchars
        tail_words = struct.unpack_from('<IIIII', buf, p)   # 1, 1, 0, 1, 0
        p += 20
        entries.append(PartitionTableEntry(guid, zero0, id_a, id_b, minus_one, kind,
                                           name, (flag,) + tail_words))
    return PartitionTable(cls, version, count, entries, buf[p:])


def load_partition_table(project: str) -> PartitionTable:
    path = os.path.join(EXTRACTED, project, 'Global__PartitionTable.gz', '000.bin')
    with open(path, 'rb') as fh:
        return parse_partition_table(fh.read())


